from __future__ import annotations

from pathlib import PurePosixPath

from treeforge.android.device_tree.model import (
    AndroidDeviceTreeIdentity,
)


class AndroidDeviceTreeFragmentSpineRenderer:
    """
    Render TreeForge's self-contained Device Tree composition spine.

    Fragment paths describe generic Device Tree capability families.
    They do not encode OEM/reference-tree inheritance.

    Reference Android source trees may inform what TreeForge must realize,
    but generated top-level build files consume only TreeForge-owned
    fragments and explicitly retained checkout/platform providers.
    """

    @staticmethod
    def _validate_identity(
        identity: AndroidDeviceTreeIdentity,
    ) -> None:
        if not isinstance(
            identity,
            AndroidDeviceTreeIdentity,
        ):
            raise TypeError(
                "identity must be an AndroidDeviceTreeIdentity"
            )

    @classmethod
    def render_board_config(
        cls,
        *,
        identity: AndroidDeviceTreeIdentity,
        fragments: tuple[
            PurePosixPath,
            ...,
        ],
    ) -> str:
        cls._validate_identity(identity)

        if (
            not isinstance(fragments, tuple)
            or not all(
                isinstance(item, PurePosixPath)
                for item in fragments
            )
        ):
            raise TypeError(
                "fragments must be tuple[PurePosixPath, ...]"
            )

        if len(fragments) != len(set(fragments)):
            raise ValueError(
                "BoardConfig fragment paths must be unique"
            )

        lines = [
            "# Generated by TreeForge.",
            "#",
            "# Self-contained Device Tree BoardConfig spine.",
            "# Individual capability families are generated beneath the device root.",
            "",
        ]

        for fragment in fragments:
            lines.append(
                f"include {fragment.as_posix()}"
            )

        lines.append("")

        return "\n".join(lines)

