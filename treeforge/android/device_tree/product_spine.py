from __future__ import annotations

from treeforge.android.device_tree.model import (
    AndroidDeviceTreeIdentity,
)
from treeforge.android.device_tree.product_policy import (
    AndroidDeviceTreeProductPolicy,
)


class AndroidDeviceTreeProductSpineRenderer:
    """
    Render the concrete Android product registration spine.

    Vendor payload integration remains owned by product_makefile.py.
    This renderer owns top-level product inheritance and registration only.
    """

    @staticmethod
    def render_device_makefile(
        *,
        identity: AndroidDeviceTreeIdentity,
    ) -> str:
        if not isinstance(
            identity,
            AndroidDeviceTreeIdentity,
        ):
            raise TypeError(
                "identity must be an AndroidDeviceTreeIdentity"
            )

        return (
            "# Generated by TreeForge.\n"
            "#\n"
            "# Device-specific integration consumed by the generated "
            "product.\n"
            "\n"
            "$(call inherit-product, "
            f"{identity.device_root.as_posix()}/"
            f"{identity.build_device}-vendor.mk)\n"
        )

    @staticmethod
    def product_source_root_dirs(
        *,
        identity: AndroidDeviceTreeIdentity,
    ) -> tuple[str, ...]:
        """
        Do not prune Android's Soong source graph.

        The AOSP manifest owns checkout population. TreeForge isolates only
        concrete conflicting reference/device-tree projects at the manifest
        boundary; generic Google/AOSP providers must remain visible so their
        namespaces and dependency defaults can resolve normally.
        """

        if not isinstance(
            identity,
            AndroidDeviceTreeIdentity,
        ):
            raise TypeError(
                "identity must be an AndroidDeviceTreeIdentity"
            )

        return ()

    @staticmethod
    def render_product_makefile(
        *,
        identity: AndroidDeviceTreeIdentity,
        policy: AndroidDeviceTreeProductPolicy,
        use_dynamic_partitions: bool = False,
    ) -> str:
        if not isinstance(
            identity,
            AndroidDeviceTreeIdentity,
        ):
            raise TypeError(
                "identity must be an AndroidDeviceTreeIdentity"
            )

        if not isinstance(
            policy,
            AndroidDeviceTreeProductPolicy,
        ):
            raise TypeError(
                "policy must be an AndroidDeviceTreeProductPolicy"
            )

        if not isinstance(
            use_dynamic_partitions,
            bool,
        ):
            raise TypeError(
                "use_dynamic_partitions must be a bool"
            )

        lines = [
            "# Generated by TreeForge.",
            "#",
            "# Canonical Android product policy.",
            "",
        ]

        for makefile in (
            policy.base_product_makefiles
        ):
            lines.append(
                "$(call inherit-product, "
                f"{makefile})"
            )

        lines.extend(
            [
                "",
                f"$(call inherit-product, {identity.device_root.as_posix()}/device.mk)",
                "",
                "# TreeForge-generated Soong source root.",
                "#",
                (
                    "# TreeForge declares the source root it "
                    "materialized; the TreeForge AOSP manifest "
                    "owns project-population pruning."
                ),
            ]
        )

        source_root_dirs = (
            AndroidDeviceTreeProductSpineRenderer
            .product_source_root_dirs(
                identity=identity,
            )
        )

        if source_root_dirs:
            lines.append(
                "PRODUCT_SOURCE_ROOT_DIRS += \\"
            )

            last_index = (
                len(
                    source_root_dirs
                )
                - 1
            )

            for index, source_root in enumerate(
                source_root_dirs
            ):
                suffix = (
                    " \\"
                    if index != last_index
                    else ""
                )

                lines.append(
                    f"    {source_root}{suffix}"
                )

        if use_dynamic_partitions:
            lines.extend(
                [
                    "",
                    "# Canonical factory-derived dynamic-partition topology.",
                    "PRODUCT_USE_DYNAMIC_PARTITIONS := true",
                ]
            )

        lines.extend(
            [
                "",
                f"PRODUCT_NAME := {identity.product}",
                (
                    "PRODUCT_DEVICE := "
                    f"{identity.build_device}"
                ),
                f"PRODUCT_BRAND := {policy.product_brand}",
                f"PRODUCT_MODEL := {policy.product_model}",
                (
                    "PRODUCT_MANUFACTURER := "
                    f"{policy.product_manufacturer}"
                ),
                "",
            ]
        )

        return "\n".join(
            lines
        )



    @staticmethod
    def render_android_products(
        *,
        identity: AndroidDeviceTreeIdentity,
    ) -> str:
        if not isinstance(
            identity,
            AndroidDeviceTreeIdentity,
        ):
            raise TypeError(
                "identity must be an AndroidDeviceTreeIdentity"
            )

        return (
            "# Generated by TreeForge.\n"
            "\n"
            "PRODUCT_MAKEFILES := \\\n"
            f"    $(LOCAL_DIR)/{identity.product}.mk\n"
            "\n"
            "COMMON_LUNCH_CHOICES := \\\n"
            f"    {identity.product}-bp1a-userdebug\n"
        )
