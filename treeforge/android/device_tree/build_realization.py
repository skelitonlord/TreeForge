class AndroidDeviceTreeBuildRealizationKind(
    StrEnum,
):
    """
    Concrete source-tree/build mechanism selected by Device Tree.

    These values remain independent of Android.bp versus Android.mk syntax.
    Renderers may later map the same realization into the appropriate Android
    build-language form without changing the canonical Device Tree decision.
    """

    EXISTING_SOURCE_MODULE = "existing_source_module"
    GENERATED_SOURCE = "generated_source"
    PREBUILT_MODULE = "prebuilt_module"
    COPY_FILE = "copy_file"
    PRODUCT_PACKAGE = "product_package"
    APEX_MODULE = "apex_module"
    KERNEL_MODULE = "kernel_module"
    SOURCE_CONFIG = "source_config"
    VINTF_DOCUMENT = "vintf_document"
    SELINUX_POLICY = "selinux_policy"
    SELINUX_RUNTIME_OUTPUT = "selinux_runtime_output"
    BOARD_CONFIGURATION = "board_configuration"
    PRESERVED_ONLY = "preserved_only"


class AndroidDeviceTreeBuildRealizationStatus(
    StrEnum,
):
    """
    Device Tree disposition for one Reconstruction build representation.

    RESOLVED means Device Tree can select a concrete source-tree/build
    mechanism without unsupported inference.

    CLOSED means canonical participation is fully accounted for, but no
    independent Device Tree source/build object is required. Typical cases
    include container-owned payloads and outputs regenerated by an owning
    Android build mechanism.

    PARTIAL means Device Tree preserves known physical/source participation
    but still lacks one or more concrete downstream build facts.
    """

    RESOLVED = "resolved"
    CLOSED = "closed"
    PARTIAL = "partial"


@dataclass(frozen=True, slots=True)
class AndroidDeviceTreeBuildRealization:
    """
    One exact Reconstruction build representation realized by Device Tree.

    Device Tree owns the concrete source-tree mechanism and destination layer.
    It does not reinterpret canonical runtime semantics or replace the
    Reconstruction build role.

    ``source_path`` is a Device Tree workspace-relative source path when the
    realization owns/generated/copies a physical source payload.

    ``module_name`` is populated only when Device Tree has an exact module
    identity suitable for concrete build declaration or product consumption.

    ``dependency_realization_ids`` preserves physical build dependencies
    after representation -> realization projection. It contains realization
    identities, not raw canonical relationship identities.
    """

    realization_id: str

    kind: AndroidDeviceTreeBuildRealizationKind
    status: AndroidDeviceTreeBuildRealizationStatus

    build_representation: AndroidReconstructionBuildRepresentation

    source_path: PurePosixPath | None = None
    module_name: str | None = None

    dependency_realization_ids: tuple[str, ...] = ()

    reason: str | None = None

    def __post_init__(self) -> None:
        if (
            not isinstance(
                self.realization_id,
                str,
            )
            or not self.realization_id
        ):
            raise ValueError(
                "realization_id must be a non-empty string"
            )

        if not isinstance(
            self.kind,
            AndroidDeviceTreeBuildRealizationKind,
        ):
            raise TypeError(
                "kind must be an "
                "AndroidDeviceTreeBuildRealizationKind"
            )

        if not isinstance(
            self.status,
            AndroidDeviceTreeBuildRealizationStatus,
        ):
            raise TypeError(
                "status must be an "
                "AndroidDeviceTreeBuildRealizationStatus"
            )

        if not isinstance(
            self.build_representation,
            AndroidReconstructionBuildRepresentation,
        ):
            raise TypeError(
                "build_representation must be an "
                "AndroidReconstructionBuildRepresentation"
            )

        if (
            self.source_path is not None
            and not isinstance(
                self.source_path,
                PurePosixPath,
            )
        ):
            raise TypeError(
                "source_path must be a PurePosixPath or None"
            )

        if (
            self.source_path is not None
            and self.source_path.is_absolute()
        ):
            raise ValueError(
                "source_path must be relative to the "
                "Device Tree workspace"
            )

        if (
            self.source_path is not None
            and ".." in self.source_path.parts
        ):
            raise ValueError(
                "source_path must not escape the "
                "Device Tree workspace"
            )

        for field_name, value in (
            ("module_name", self.module_name),
            ("reason", self.reason),
        ):
            if (
                value is not None
                and (
                    not isinstance(value, str)
                    or not value
                )
            ):
                raise ValueError(
                    f"{field_name} must be a non-empty "
                    "string or None"
                )

        if not isinstance(
            self.dependency_realization_ids,
            tuple,
        ):
            raise TypeError(
                "dependency_realization_ids must be a tuple"
            )

        if not all(
            isinstance(value, str) and value
            for value
            in self.dependency_realization_ids
        ):
            raise ValueError(
                "dependency_realization_ids must contain only "
                "non-empty strings"
            )

        if len(
            self.dependency_realization_ids
        ) != len(
            set(
                self.dependency_realization_ids
            )
        ):
            raise ValueError(
                "dependency_realization_ids must be unique"
            )

        if (
            self.dependency_realization_ids
            != tuple(
                sorted(
                    self.dependency_realization_ids
                )
            )
        ):
            raise ValueError(
                "dependency_realization_ids must use "
                "deterministic ordering"
            )

        if (
            self.realization_id
            in self.dependency_realization_ids
        ):
            raise ValueError(
                "Device Tree build realization must not "
                "depend on itself"
            )

        if (
            self.status
            in {
                AndroidDeviceTreeBuildRealizationStatus.CLOSED,
                AndroidDeviceTreeBuildRealizationStatus.PARTIAL,
            }
            and self.reason is None
        ):
            raise ValueError(
                f"{self.status.value.upper()} Device Tree build "
                "realization requires a reason"
            )

    @property
    def representation_id(self) -> str:
        return self.build_representation.representation_id



@dataclass(frozen=True, slots=True)
class AndroidDeviceTreeBuildRealizationCoverage:
    """
    Global coverage summary for Reconstruction -> Device Tree realization.

    This is structural accounting only. Family projectors remain authoritative
    for selecting the concrete Device Tree realization kind.
    """

    reconstruction_representation_count: int
    realization_count: int
    realized_representation_count: int

    dependency_edge_count: int

    missing_representation_count: int
    duplicate_representation_count: int
    invalid_dependency_target_count: int
    dependency_projection_mismatch_count: int

    complete: bool

    def __post_init__(self) -> None:
        for field_name, value in (
            (
                "reconstruction_representation_count",
                self.reconstruction_representation_count,
            ),
            (
                "realization_count",
                self.realization_count,
            ),
            (
                "realized_representation_count",
                self.realized_representation_count,
            ),
            (
                "dependency_edge_count",
                self.dependency_edge_count,
            ),
            (
                "missing_representation_count",
                self.missing_representation_count,
            ),
            (
                "duplicate_representation_count",
                self.duplicate_representation_count,
            ),
            (
                "invalid_dependency_target_count",
                self.invalid_dependency_target_count,
            ),
            (
                "dependency_projection_mismatch_count",
                self.dependency_projection_mismatch_count,
            ),
        ):
            if (
                not isinstance(value, int)
                or isinstance(value, bool)
                or value < 0
            ):
                raise ValueError(
                    f"{field_name} must be a non-negative integer"
                )

        if not isinstance(
            self.complete,
            bool,
        ):
            raise TypeError(
                "complete must be a bool"
            )


class AndroidDeviceTreeBuildRealizationValidator:
    """
    Validate the completed Reconstruction -> Device Tree realization graph.

    The validator never chooses a realization kind and never infers missing
    Device Tree policy. It verifies only global structural invariants after
    family projectors have made their own decisions.

    Final Device Tree acceptance requires:

    - exactly one realization per Reconstruction build representation;
    - every realization retains the exact Reconstruction representation
      object;
    - realization identities are unique;
    - representation identities are covered exactly once;
    - dependency realization references target existing realizations;
    - realization dependencies exactly project Reconstruction dependency_ids.
    """

    @classmethod
    def validate(
        cls,
        *,
        build_representations: tuple[
            AndroidReconstructionBuildRepresentation,
            ...,
        ],
        realizations: tuple[
            AndroidDeviceTreeBuildRealization,
            ...,
        ],
    ) -> AndroidDeviceTreeBuildRealizationCoverage:
        if not isinstance(
            build_representations,
            tuple,
        ):
            raise TypeError(
                "build_representations must be a tuple"
            )

        if not all(
            isinstance(
                representation,
                AndroidReconstructionBuildRepresentation,
            )
            for representation
            in build_representations
        ):
            raise TypeError(
                "build_representations must contain only "
                "AndroidReconstructionBuildRepresentation values"
            )

        if not isinstance(
            realizations,
            tuple,
        ):
            raise TypeError(
                "realizations must be a tuple"
            )

        if not all(
            isinstance(
                realization,
                AndroidDeviceTreeBuildRealization,
            )
            for realization
            in realizations
        ):
            raise TypeError(
                "realizations must contain only "
                "AndroidDeviceTreeBuildRealization values"
            )

        reconstruction_by_id = {
            representation.representation_id:
            representation
            for representation
            in build_representations
        }

        if len(
            reconstruction_by_id
        ) != len(
            build_representations
        ):
            raise ValueError(
                "Reconstruction build representation identities "
                "must be unique before Device Tree"
            )

        realization_ids = tuple(
            realization.realization_id
            for realization
            in realizations
        )

        if len(realization_ids) != len(
            set(realization_ids)
        ):
            raise ValueError(
                "Device Tree build realization identities "
                "must be globally unique"
            )

        realization_by_representation_id = {}
        duplicate_representation_count = 0

        for realization in realizations:
            representation = (
                realization.build_representation
            )

            canonical = reconstruction_by_id.get(
                representation.representation_id
            )

            if canonical is None:
                raise ValueError(
                    "Device Tree build realization references "
                    "a representation outside the supplied "
                    "Reconstruction build population: "
                    f"{representation.representation_id}"
                )

            if canonical is not representation:
                raise ValueError(
                    "Device Tree build realization must preserve "
                    "the exact Reconstruction build representation "
                    "object identity: "
                    f"{representation.representation_id}"
                )

            representation_id = (
                representation.representation_id
            )

            if (
                representation_id
                in realization_by_representation_id
            ):
                duplicate_representation_count += 1
                continue

            realization_by_representation_id[
                representation_id
            ] = realization

        missing_representation_ids = (
            set(reconstruction_by_id)
            - set(
                realization_by_representation_id
            )
        )

        realization_by_id = {
            realization.realization_id:
            realization
            for realization
            in realizations
        }

        invalid_dependency_target_count = 0
        dependency_projection_mismatch_count = 0
        dependency_edge_count = 0

        for realization in realizations:
            dependency_edge_count += len(
                realization.dependency_realization_ids
            )

            for dependency_realization_id in (
                realization
                .dependency_realization_ids
            ):
                if (
                    dependency_realization_id
                    not in realization_by_id
                ):
                    invalid_dependency_target_count += 1

            expected_dependency_realization_ids = []

            for dependency_representation_id in (
                realization
                .build_representation
                .dependency_ids
            ):
                dependency_realization = (
                    realization_by_representation_id
                    .get(
                        dependency_representation_id
                    )
                )

                if dependency_realization is None:
                    continue

                expected_dependency_realization_ids.append(
                    dependency_realization.realization_id
                )

            expected_dependency_realization_ids = tuple(
                sorted(
                    expected_dependency_realization_ids
                )
            )

            if (
                realization.dependency_realization_ids
                != expected_dependency_realization_ids
            ):
                dependency_projection_mismatch_count += 1

        complete = (
            len(realizations)
            == len(build_representations)
            and len(realization_by_representation_id)
            == len(build_representations)
            and not missing_representation_ids
            and duplicate_representation_count == 0
            and invalid_dependency_target_count == 0
            and dependency_projection_mismatch_count == 0
        )

        return AndroidDeviceTreeBuildRealizationCoverage(
            reconstruction_representation_count=(
                len(build_representations)
            ),
            realization_count=len(realizations),
            realized_representation_count=(
                len(
                    realization_by_representation_id
                )
            ),
            dependency_edge_count=(
                dependency_edge_count
            ),
            missing_representation_count=(
                len(
                    missing_representation_ids
                )
            ),
            duplicate_representation_count=(
                duplicate_representation_count
            ),
            invalid_dependency_target_count=(
                invalid_dependency_target_count
            ),
            dependency_projection_mismatch_count=(
                dependency_projection_mismatch_count
            ),
            complete=complete,
        )



class AndroidDeviceTreeSourceBuildRealizationProjector:
    """
    Realize exact source-content-backed Reconstruction build participation.

    Reconstruction already proves which source-content units participate in
    the Android build. Device Tree already chooses deterministic physical
    source-tree destinations for those same content units.

    This projector joins those two canonical identities by source_content_id.

    It deliberately does not:
    - reinterpret source semantics;
    - include NOT_SOURCE_DECLARABLE runtime-property content;
    - consume requirement-backed SOURCE_CONFIG values such as modules.*;
    - choose Make versus Soong syntax;
    - choose product/BoardConfig integration.
    """

    @classmethod
    def project(
        cls,
        reconstruction,
        *,
        source_projections,
    ) -> tuple[
        AndroidDeviceTreeBuildRealization,
        ...,
    ]:
        from treeforge.android.device_tree.projection import (
            AndroidDeviceTreeSourceProjection,
        )
        from treeforge.android.reconstruction.model import (
            AndroidReconstructionResult,
        )

        if not isinstance(
            reconstruction,
            AndroidReconstructionResult,
        ):
            raise TypeError(
                "reconstruction must be an "
                "AndroidReconstructionResult"
            )

        if not isinstance(
            source_projections,
            tuple,
        ):
            raise TypeError(
                "source_projections must be a tuple"
            )

        if not all(
            isinstance(
                projection,
                AndroidDeviceTreeSourceProjection,
            )
            for projection
            in source_projections
        ):
            raise TypeError(
                "source_projections must contain only "
                "AndroidDeviceTreeSourceProjection values"
            )

        projection_by_content_id = {
            projection.content_id: projection
            for projection
            in source_projections
        }

        if len(
            projection_by_content_id
        ) != len(
            source_projections
        ):
            raise ValueError(
                "Device Tree source projections must preserve "
                "unique Reconstruction content identities"
            )

        source_backed_representations = tuple(
            representation
            for representation
            in reconstruction.artifact_build_representations
            if representation.source_content_id is not None
        )

        representation_by_content_id = {
            representation.source_content_id:
            representation
            for representation
            in source_backed_representations
        }

        if len(
            representation_by_content_id
        ) != len(
            source_backed_representations
        ):
            raise ValueError(
                "source-content-backed Reconstruction build "
                "representations must preserve unique content identity"
            )

        expected_content_ids = set(
            representation_by_content_id
        )

        projected_content_ids = set(
            projection_by_content_id
        )

        if projected_content_ids != expected_content_ids:
            missing_projection_ids = sorted(
                expected_content_ids
                - projected_content_ids
            )

            unexpected_projection_ids = sorted(
                projected_content_ids
                - expected_content_ids
            )

            raise ValueError(
                "Device Tree source projection/build representation "
                "coverage mismatch: "
                f"missing_projection="
                f"{missing_projection_ids!r}, "
                f"unexpected_projection="
                f"{unexpected_projection_ids!r}"
            )

        realizations = []

        for content_id in sorted(
            representation_by_content_id
        ):
            representation = (
                representation_by_content_id[
                    content_id
                ]
            )

            projection = (
                projection_by_content_id[
                    content_id
                ]
            )

            realizations.append(
                AndroidDeviceTreeBuildRealization(
                    realization_id=(
                        "device-tree-realization:"
                        f"{representation.representation_id}"
                    ),
                    kind=(
                        AndroidDeviceTreeBuildRealizationKind
                        .GENERATED_SOURCE
                    ),
                    status=(
                        AndroidDeviceTreeBuildRealizationStatus
                        .RESOLVED
                    ),
                    build_representation=representation,
                    source_path=projection.destination,
                    module_name=None,
                    dependency_realization_ids=(),
                    reason=None,
                )
            )

        result = tuple(
            sorted(
                realizations,
                key=lambda realization: (
                    realization.realization_id
                ),
            )
        )

        represented_ids = tuple(
            realization.representation_id
            for realization
            in result
        )

        expected_representation_ids = {
            representation.representation_id
            for representation
            in source_backed_representations
        }

        if set(
            represented_ids
        ) != expected_representation_ids:
            raise ValueError(
                "source-backed Device Tree realizations must "
                "cover the source-backed Reconstruction build "
                "population exactly"
            )

        if len(
            represented_ids
        ) != len(
            set(
                represented_ids
            )
        ):
            raise ValueError(
                "source-backed Device Tree realizations must "
                "contain each Reconstruction representation "
                "exactly once"
            )

        return result



class AndroidDeviceTreePreservedBuildRealizationProjector:
    """
    Realize exact preserved canonical Artifact payloads.

    Deployment role remains authoritative for whether one preserved Artifact
    may exist as an independent Device Tree source artifact.

    DIRECT_PARTITION artifacts must already have an exact Device Tree
    artifact projection and become COPY_FILE realizations.

    BOOT_FILESYSTEM and NESTED_FILESYSTEM artifacts remain owned by their
    physical container and become PRESERVED_ONLY realizations. They must not
    be copied independently into the generated proprietary tree.
    """

    @classmethod
    def project(
        cls,
        reconstruction,
        *,
        artifact_projections,
    ) -> tuple[
        AndroidDeviceTreeBuildRealization,
        ...,
    ]:
        from treeforge.android.device_tree.artifact_projection import (
            AndroidDeviceTreeArtifactProjection,
        )
        from treeforge.android.reconstruction.model import (
            AndroidReconstructionResult,
        )
        from treeforge.android.universe.artifact.model import (
            AndroidUniverseArtifactDeploymentRole,
            AndroidUniverseArtifactRequirement,
        )

        if not isinstance(
            reconstruction,
            AndroidReconstructionResult,
        ):
            raise TypeError(
                "reconstruction must be an "
                "AndroidReconstructionResult"
            )

        if not isinstance(
            artifact_projections,
            tuple,
        ):
            raise TypeError(
                "artifact_projections must be a tuple"
            )

        if not all(
            isinstance(
                projection,
                AndroidDeviceTreeArtifactProjection,
            )
            for projection
            in artifact_projections
        ):
            raise TypeError(
                "artifact_projections must contain only "
                "AndroidDeviceTreeArtifactProjection values"
            )

        ownership = (
            reconstruction
            .reconstruction_input
            .plan
            .ownership
        )

        if ownership is None:
            raise ValueError(
                "preserved-backed Device Tree realization "
                "requires first-class Reconstruction Ownership"
            )

        preserved_representations = tuple(
            representation
            for representation
            in reconstruction.artifact_build_representations
            if representation.preserved_artifact_id is not None
        )

        representation_by_artifact_id = {
            representation.preserved_artifact_id:
            representation
            for representation
            in preserved_representations
        }

        if len(
            representation_by_artifact_id
        ) != len(
            preserved_representations
        ):
            raise ValueError(
                "preserved-backed Reconstruction representations "
                "must preserve unique Artifact identity"
            )

        projection_by_artifact_id = {
            projection.artifact_id:
            projection
            for projection
            in artifact_projections
        }

        if len(
            projection_by_artifact_id
        ) != len(
            artifact_projections
        ):
            raise ValueError(
                "Device Tree Artifact projections must preserve "
                "unique Artifact identity"
            )

        realizations = []

        for artifact_id in sorted(
            representation_by_artifact_id
        ):
            representation = (
                representation_by_artifact_id[
                    artifact_id
                ]
            )

            ownership_decision = (
                ownership.decision_for(
                    requirement_kind="artifact",
                    source_identity=artifact_id,
                )
            )

            if ownership_decision is None:
                raise ValueError(
                    "preserved-backed representation has no "
                    "Artifact Ownership decision: "
                    f"{artifact_id}"
                )

            requirement = (
                ownership_decision.requirement
            )

            if not isinstance(
                requirement,
                AndroidUniverseArtifactRequirement,
            ):
                raise TypeError(
                    "preserved-backed Artifact Ownership must "
                    "retain an AndroidUniverseArtifactRequirement"
                )

            if (
                requirement.requirement_id
                != artifact_id
            ):
                raise ValueError(
                    "preserved-backed realization changed exact "
                    "canonical Artifact identity"
                )

            deployment_role = (
                requirement.deployment_role
            )

            if (
                deployment_role
                is AndroidUniverseArtifactDeploymentRole
                .DIRECT_PARTITION
            ):
                from treeforge.android.device_tree.preserved_artifact_policy import (
                    preserved_artifact_requires_source_materialization,
                )

                projection = (
                    projection_by_artifact_id.get(
                        artifact_id
                    )
                )

                requires_source_materialization = (
                    preserved_artifact_requires_source_materialization(
                        requirement
                    )
                )

                if not requires_source_materialization:
                    if projection is not None:
                        raise ValueError(
                            "runtime/generated preserved Artifact "
                            "must not have an independent Device Tree "
                            "artifact projection: "
                            f"{artifact_id}"
                        )

                    realization_kind = (
                        AndroidDeviceTreeBuildRealizationKind
                        .PRESERVED_ONLY
                    )

                    source_path = None

                else:
                    if projection is None:
                        raise ValueError(
                            "DIRECT_PARTITION preserved Artifact "
                            "requires an exact Device Tree "
                            "artifact projection: "
                            f"{artifact_id}"
                        )

                    if (
                        projection.build_representation
                        is not representation
                    ):
                        raise ValueError(
                            "DIRECT_PARTITION Artifact projection "
                            "changed exact Reconstruction build "
                            "representation identity"
                        )

                    realization_kind = (
                        AndroidDeviceTreeBuildRealizationKind
                        .COPY_FILE
                    )

                    source_path = (
                        projection.destination
                    )

            elif deployment_role in {
                AndroidUniverseArtifactDeploymentRole
                .BOOT_FILESYSTEM,
                AndroidUniverseArtifactDeploymentRole
                .NESTED_FILESYSTEM,
            }:
                if artifact_id in projection_by_artifact_id:
                    raise ValueError(
                        "container-resident preserved Artifact "
                        "must not have an independent Device Tree "
                        "artifact projection: "
                        f"{artifact_id}"
                    )

                realization_kind = (
                    AndroidDeviceTreeBuildRealizationKind
                    .PRESERVED_ONLY
                )

                source_path = None

            else:
                raise ValueError(
                    "preserved-backed Device Tree realization "
                    "does not yet support deployment role "
                    f"{deployment_role.value!r}: "
                    f"{artifact_id}"
                )

            realizations.append(
                AndroidDeviceTreeBuildRealization(
                    realization_id=(
                        "device-tree-realization:"
                        f"{representation.representation_id}"
                    ),
                    kind=realization_kind,
                    status=(
                        AndroidDeviceTreeBuildRealizationStatus
                        .RESOLVED
                    ),
                    build_representation=representation,
                    source_path=source_path,
                    module_name=None,
                    dependency_realization_ids=(),
                    reason=None,
                )
            )

        result = tuple(
            sorted(
                realizations,
                key=lambda realization: (
                    realization.realization_id
                ),
            )
        )

        represented_ids = {
            realization.representation_id
            for realization
            in result
        }

        expected_ids = {
            representation.representation_id
            for representation
            in preserved_representations
        }

        if represented_ids != expected_ids:
            raise ValueError(
                "preserved-backed Device Tree realization "
                "coverage mismatch"
            )

        if len(result) != len(
            represented_ids
        ):
            raise ValueError(
                "preserved-backed Device Tree realizations "
                "must cover each Reconstruction representation "
                "exactly once"
            )

        return result



class AndroidDeviceTreePackageBuildRealizationProjector:
    """
    Realize canonical APK/RRO build participation.

    Reconstruction PACKAGE representations retain exact canonical package
    Artifact identity, installed partition/path, and physical dependencies.

    Device Tree selects a concrete mechanism only when an exact
    DIRECT_PARTITION physical payload projection exists.

    Direct package payloads are classified mechanically from their canonical
    installed path:

    - every independently materializable package payload becomes a
      COPY_FILE realization preserving its exact observed install path.

    Ordinary app/priv-app module declarations are intentionally not invented:
    Android Make and Soong both couple the installed app directory to module
    identity, while canonical evidence does not establish the OEM's original
    source-module identity.

    Package representations without an independently materializable physical
    payload remain PARTIAL PRODUCT_PACKAGE until a later Device Tree mechanism
    can be established without unsupported inference.

    """

    _LOGICAL_PARTITIONS = {
        "system",
        "vendor",
        "product",
        "system_ext",
        "odm",
    }

    @classmethod
    def project(
        cls,
        reconstruction,
        *,
        existing_realizations: tuple[
            AndroidDeviceTreeBuildRealization,
            ...,
        ],
        physical_payload_projections,
    ) -> tuple[
        AndroidDeviceTreeBuildRealization,
        ...,
    ]:
        from treeforge.android.device_tree.physical_payload_projection import (
            AndroidDeviceTreePhysicalPayloadProjection,
        )
        from treeforge.android.reconstruction.build_system.model import (
            AndroidReconstructionBuildRepresentationKind,
        )
        from treeforge.android.reconstruction.model import (
            AndroidReconstructionResult,
        )

        if not isinstance(
            reconstruction,
            AndroidReconstructionResult,
        ):
            raise TypeError(
                "reconstruction must be an "
                "AndroidReconstructionResult"
            )

        if not isinstance(
            existing_realizations,
            tuple,
        ):
            raise TypeError(
                "existing_realizations must be a tuple"
            )

        if not all(
            isinstance(
                realization,
                AndroidDeviceTreeBuildRealization,
            )
            for realization
            in existing_realizations
        ):
            raise TypeError(
                "existing_realizations must contain only "
                "AndroidDeviceTreeBuildRealization values"
            )

        if not isinstance(
            physical_payload_projections,
            tuple,
        ):
            raise TypeError(
                "physical_payload_projections must be a tuple"
            )

        if not all(
            isinstance(
                projection,
                AndroidDeviceTreePhysicalPayloadProjection,
            )
            for projection
            in physical_payload_projections
        ):
            raise TypeError(
                "physical_payload_projections must contain only "
                "AndroidDeviceTreePhysicalPayloadProjection values"
            )

        physical_by_representation_id = {
            projection.representation_id:
            projection
            for projection
            in physical_payload_projections
        }

        if len(
            physical_by_representation_id
        ) != len(
            physical_payload_projections
        ):
            raise ValueError(
                "physical payload projections must preserve "
                "unique Reconstruction representation identity"
            )

        package_representations = tuple(
            representation
            for representation
            in reconstruction.artifact_build_representations
            if (
                representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .PACKAGE
            )
        )

        if not package_representations:
            return ()

        existing_representation_ids = {
            realization.representation_id
            for realization
            in existing_realizations
        }

        package_representation_ids = {
            representation.representation_id
            for representation
            in package_representations
        }

        overlap = (
            existing_representation_ids
            & package_representation_ids
        )

        if overlap:
            raise ValueError(
                "PACKAGE realization population overlaps existing "
                "Device Tree representation coverage: "
                f"{sorted(overlap)!r}"
            )

        all_representation_ids = {
            representation.representation_id
            for representation
            in reconstruction.artifact_build_representations
        }

        realizations = []

        for representation in package_representations:
            if (
                representation.canonical_requirement_id
                is None
            ):
                raise ValueError(
                    "requirement-backed PACKAGE representation "
                    "must retain canonical_requirement_id: "
                    f"{representation.representation_id}"
                )

            if (
                representation.preserved_artifact_id
                is not None
            ):
                raise ValueError(
                    "PACKAGE realization must not re-realize "
                    "preserved-backed package payloads: "
                    f"{representation.representation_id}"
                )

            missing_dependency_ids = (
                set(
                    representation.dependency_ids
                )
                - all_representation_ids
            )

            if missing_dependency_ids:
                raise ValueError(
                    "PACKAGE representation references missing "
                    "Reconstruction dependency identities: "
                    f"{representation.representation_id}, "
                    f"missing={sorted(missing_dependency_ids)!r}"
                )

            dependency_realization_ids = tuple(
                sorted(
                    (
                        "device-tree-realization:"
                        f"{dependency_id}"
                    )
                    for dependency_id
                    in representation.dependency_ids
                )
            )

            physical_projection = (
                physical_by_representation_id.get(
                    representation.representation_id
                )
            )

            if physical_projection is None:
                realizations.append(
                    AndroidDeviceTreeBuildRealization(
                        realization_id=(
                            "device-tree-realization:"
                            f"{representation.representation_id}"
                        ),
                        kind=(
                            AndroidDeviceTreeBuildRealizationKind
                            .PRODUCT_PACKAGE
                        ),
                        status=(
                            AndroidDeviceTreeBuildRealizationStatus
                            .CLOSED
                        ),
                        build_representation=representation,
                        source_path=None,
                        module_name=None,
                        dependency_realization_ids=(
                            dependency_realization_ids
                        ),
                        reason=(
                            "Canonical package participation is known, "
                            "but this PACKAGE representation has no "
                            "independently materializable DIRECT_PARTITION "
                            "physical payload."
                        ),
                    )
                )

                continue

            if (
                physical_projection.build_representation
                is not representation
            ):
                raise ValueError(
                    "PACKAGE physical payload projection changed "
                    "exact Reconstruction representation identity: "
                    f"{representation.representation_id}"
                )

            if (
                physical_projection.requirement_id
                != representation.canonical_requirement_id
            ):
                raise ValueError(
                    "PACKAGE physical payload projection changed "
                    "canonical Artifact requirement identity: "
                    f"{representation.representation_id}"
                )

            source_path = (
                physical_projection.destination
            )

            installed_path = PurePosixPath(
                physical_projection.installed_android_path
            )

            if not installed_path.is_absolute():
                raise ValueError(
                    "PACKAGE installed Android path must be absolute: "
                    f"{representation.representation_id}"
                )

            parts = list(
                installed_path.parts[1:]
            )

            if not parts:
                raise ValueError(
                    "PACKAGE installed Android path must identify "
                    "a file: "
                    f"{representation.representation_id}"
                )

            physical_partition = (
                physical_projection.installed_partition
            )

            if (
                parts
                and parts[0]
                == physical_partition
            ):
                parts = parts[1:]

            if not parts:
                raise ValueError(
                    "PACKAGE installed path became empty after "
                    "physical partition normalization: "
                    f"{representation.representation_id}"
                )

            logical_partition = (
                physical_partition
            )

            if (
                logical_partition
                not in cls._LOGICAL_PARTITIONS
            ):
                if (
                    parts
                    and parts[0]
                    in cls._LOGICAL_PARTITIONS
                ):
                    logical_partition = parts.pop(0)
                else:
                    raise ValueError(
                        "PACKAGE realization cannot derive a "
                        "supported logical Android partition from "
                        "canonical evidence: "
                        f"physical_partition="
                        f"{physical_partition!r}, "
                        f"installed_path="
                        f"{physical_projection.installed_android_path!r}, "
                        f"representation="
                        f"{representation.representation_id}"
                    )

            if not parts:
                raise ValueError(
                    "PACKAGE logical install path must identify "
                    "a file: "
                    f"{representation.representation_id}"
                )

            install_class = parts[0]

            path_after_class = parts[1:]

            filename = parts[-1]

            filename_lower = (
                filename.lower()
            )

            is_plain_apk = (
                filename_lower.endswith(".apk")
                and not filename_lower.endswith(
                    ".apk.gz"
                )
            )

            is_top_level_app = (
                install_class
                in {
                    "app",
                    "priv-app",
                }
                and is_plain_apk
                and len(
                    path_after_class
                )
                == 2
            )

            is_rro_apk = (
                install_class == "overlay"
                and is_plain_apk
            )

            #
            # A top-level plain APK or canonical partition RRO has enough
            # canonical physical identity
            # for Android Make BUILD_PREBUILT. Make permits TreeForge to use
            # an independent collision-safe module identity while preserving
            # the exact install directory through LOCAL_MODULE_PATH and exact
            # filename through LOCAL_MODULE_STEM.
            #
            # Canonical /overlay/*.apk package representations are Android
            # runtime resource-overlay APKs and must participate as APK
            # prebuilts rather than PRODUCT_COPY_FILES.
            #
            # Existing irregular/nested package handling remains unchanged.
            #
            is_compressed_apk = (
                installed_path.name.lower().endswith(".apk.gz")
            )

            if (
                (
                    install_class in {"app", "priv-app"}
                    and (
                        is_plain_apk
                        or (
                            is_compressed_apk
                            and len(path_after_class) == 2
                        )
                    )
                )
                or is_plain_apk
            ):
                safe_components = (
                    (
                        [
                            install_class
                        ]
                        + path_after_class[:-1]
                    )
                    or [
                        install_class
                    ]
                )

                safe_identity = "_".join(
                    "".join(
                        character
                        if character.isalnum()
                        else "_"
                        for character
                        in component
                    )
                    for component
                    in safe_components
                )

                module_digest = sha256(
                    representation
                    .representation_id
                    .encode("utf-8")
                ).hexdigest()[:10]

                realization_kind = (
                    AndroidDeviceTreeBuildRealizationKind
                    .PREBUILT_MODULE
                )

                module_name = (
                    "treeforge_apk_"
                    f"{logical_partition}_"
                    f"{safe_identity}_"
                    f"{module_digest}"
                )

            else:
                realization_kind = (
                    AndroidDeviceTreeBuildRealizationKind
                    .COPY_FILE
                )

                module_name = None

            realizations.append(
                AndroidDeviceTreeBuildRealization(
                    realization_id=(
                        "device-tree-realization:"
                        f"{representation.representation_id}"
                    ),
                    kind=realization_kind,
                    status=(
                        AndroidDeviceTreeBuildRealizationStatus
                        .RESOLVED
                    ),
                    build_representation=representation,
                    source_path=source_path,
                    module_name=module_name,
                    dependency_realization_ids=(
                        dependency_realization_ids
                    ),
                    reason=None,
                )
            )

        result = tuple(
            sorted(
                realizations,
                key=lambda realization: (
                    realization.realization_id
                ),
            )
        )

        represented_ids = {
            realization.representation_id
            for realization
            in result
        }

        if (
            represented_ids
            != package_representation_ids
        ):
            raise ValueError(
                "Device Tree PACKAGE realization coverage mismatch"
            )

        if len(result) != len(
            represented_ids
        ):
            raise ValueError(
                "Device Tree PACKAGE realizations must cover "
                "each Reconstruction representation exactly once"
            )

        module_names = tuple(
            realization.module_name
            for realization
            in result
            if realization.module_name is not None
        )

        if len(
            module_names
        ) != len(
            set(
                module_names
            )
        ):
            raise ValueError(
                "TreeForge package module identities must be unique"
            )

        dependency_edge_count = sum(
            len(
                realization.dependency_realization_ids
            )
            for realization
            in result
        )

        expected_dependency_edge_count = sum(
            len(
                representation.dependency_ids
            )
            for representation
            in package_representations
        )

        if (
            dependency_edge_count
            != expected_dependency_edge_count
        ):
            raise ValueError(
                "Device Tree PACKAGE dependency projection "
                "coverage mismatch"
            )

        return result


class AndroidDeviceTreeElfBuildRealizationProjector:
    """
    Realize syntax-neutral native-library and executable build participation.

    Reconstruction and Runtime Linking are authoritative for:
    - exact physical canonical Artifact identity;
    - intrinsic NATIVE_LIBRARY / EXECUTABLE role;
    - installed partition/path;
    - contextual physical ELF dependencies.

    Device Tree does not repeat linker resolution or infer module identity,
    source paths, SONAME-based ownership, or Make/Soong syntax.

    Until a concrete source/prebuilt payload and module declaration are
    established downstream, each physical ELF role is represented as a
    PARTIAL PREBUILT_MODULE realization.
    """

    @classmethod
    def project(
        cls,
        reconstruction,
        *,
        existing_realizations: tuple[
            AndroidDeviceTreeBuildRealization,
            ...,
        ],
        physical_payload_projections,
    ) -> tuple[
        AndroidDeviceTreeBuildRealization,
        ...,
    ]:
        from treeforge.android.reconstruction.build_system.model import (
            AndroidReconstructionBuildRepresentationKind,
        )
        from treeforge.android.reconstruction.model import (
            AndroidReconstructionResult,
        )

        if not isinstance(
            reconstruction,
            AndroidReconstructionResult,
        ):
            raise TypeError(
                "reconstruction must be an "
                "AndroidReconstructionResult"
            )

        if not isinstance(
            existing_realizations,
            tuple,
        ):
            raise TypeError(
                "existing_realizations must be a tuple"
            )

        if not all(
            isinstance(
                realization,
                AndroidDeviceTreeBuildRealization,
            )
            for realization
            in existing_realizations
        ):
            raise TypeError(
                "existing_realizations must contain only "
                "AndroidDeviceTreeBuildRealization values"
            )

        from treeforge.android.device_tree.physical_payload_projection import (
            AndroidDeviceTreePhysicalPayloadProjection,
        )

        if not isinstance(
            physical_payload_projections,
            tuple,
        ):
            raise TypeError(
                "physical_payload_projections must be a tuple"
            )

        if not all(
            isinstance(
                projection,
                AndroidDeviceTreePhysicalPayloadProjection,
            )
            for projection
            in physical_payload_projections
        ):
            raise TypeError(
                "physical_payload_projections must contain only "
                "AndroidDeviceTreePhysicalPayloadProjection values"
            )

        elf_semantics_by_representation_id = {}

        for semantics in reconstruction.elf_build_semantics:
            target_id = (
                semantics.target_build_representation_id
            )

            if target_id is None:
                continue

            if (
                target_id
                in elf_semantics_by_representation_id
            ):
                raise ValueError(
                    "multiple ELF semantics target one "
                    "Reconstruction representation: "
                    f"{target_id}"
                )

            elf_semantics_by_representation_id[
                target_id
            ] = semantics

        physical_projection_by_representation_id = {
            projection.representation_id:
            projection
            for projection
            in physical_payload_projections
        }

        if len(
            physical_projection_by_representation_id
        ) != len(
            physical_payload_projections
        ):
            raise ValueError(
                "physical payload projections must preserve "
                "unique Reconstruction representation identity"
            )

        elf_kinds = {
            AndroidReconstructionBuildRepresentationKind
            .NATIVE_LIBRARY,
            AndroidReconstructionBuildRepresentationKind
            .EXECUTABLE,
        }

        elf_representations = tuple(
            representation
            for representation
            in reconstruction.artifact_build_representations
            if representation.kind in elf_kinds
        )

        existing_representation_ids = {
            realization.representation_id
            for realization
            in existing_realizations
        }

        elf_representation_ids = {
            representation.representation_id
            for representation
            in elf_representations
        }

        overlap = (
            existing_representation_ids
            & elf_representation_ids
        )

        if overlap:
            raise ValueError(
                "ELF realization population overlaps existing "
                "Device Tree representation coverage: "
                f"{sorted(overlap)!r}"
            )

        all_representation_ids = {
            representation.representation_id
            for representation
            in reconstruction.artifact_build_representations
        }

        realizations = []

        for representation in elf_representations:
            if (
                representation.canonical_requirement_id
                is None
            ):
                raise ValueError(
                    "Device Tree step-5 ELF realization requires "
                    "canonical requirement-backed physical identity: "
                    f"{representation.representation_id}"
                )

            if (
                representation.preserved_artifact_id
                is not None
                or representation.source_content_id
                is not None
                or representation.source_module_id
                is not None
            ):
                raise ValueError(
                    "step-5 ELF realization encountered an "
                    "unexpected non-requirement payload identity: "
                    f"{representation.representation_id}"
                )

            missing_dependency_ids = (
                set(
                    representation.dependency_ids
                )
                - all_representation_ids
            )

            if missing_dependency_ids:
                raise ValueError(
                    "ELF representation references missing "
                    "Reconstruction dependency identities: "
                    f"{representation.representation_id}, "
                    f"missing={sorted(missing_dependency_ids)!r}"
                )

            dependency_realization_ids = tuple(
                sorted(
                    (
                        "device-tree-realization:"
                        f"{dependency_id}"
                    )
                    for dependency_id
                    in representation.dependency_ids
                )
            )

            physical_projection = (
                physical_projection_by_representation_id.get(
                    representation.representation_id
                )
            )

            if physical_projection is not None:
                if (
                    physical_projection.build_representation
                    is not representation
                ):
                    raise ValueError(
                        "ELF physical payload projection changed "
                        "exact Reconstruction representation identity: "
                        f"{representation.representation_id}"
                    )

                if (
                    physical_projection.requirement_id
                    != representation.canonical_requirement_id
                ):
                    raise ValueError(
                        "ELF physical payload projection changed "
                        "canonical Artifact requirement identity: "
                        f"{representation.representation_id}"
                    )

                source_path = (
                    physical_projection.destination
                )

                installed_path = PurePosixPath(
                    representation.installed_android_path
                )

                if not installed_path.is_absolute():
                    raise ValueError(
                        "ELF build realization requires an absolute "
                        "installed Android path: "
                        f"{representation.representation_id}"
                    )

                install_parts = list(
                    installed_path.parts[1:]
                )

                if not install_parts:
                    raise ValueError(
                        "ELF build realization installed path "
                        "must identify a file: "
                        f"{representation.representation_id}"
                    )

                if install_parts[0] in {
                    "system",
                    "vendor",
                    "product",
                    "system_ext",
                    "odm",
                }:
                    install_parts = install_parts[1:]

                if len(install_parts) < 2:
                    install_base = None
                else:
                    install_base = install_parts[0]

                if (
                    representation.kind
                    is AndroidReconstructionBuildRepresentationKind
                    .NATIVE_LIBRARY
                ):
                    semantics = (
                        elf_semantics_by_representation_id
                        .get(
                            representation.representation_id
                        )
                    )

                    architecture = (
                        semantics.requirement.android_architecture
                        if semantics is not None
                        else None
                    )

                    expected_library_install_class = {
                        "arm": "lib",
                        "x86": "lib",
                        "arm64": "lib64",
                        "x86_64": "lib64",
                        "riscv64": "lib64",
                    }.get(
                        architecture
                    )

                    installed_filename = (
                        install_parts[-1]
                        if install_parts
                        else ""
                    )

                    module_backed = (
                        expected_library_install_class
                        is not None
                        and install_base
                        == expected_library_install_class
                        and installed_filename.endswith(
                            ".so"
                        )
                    )

                else:
                    module_backed = (
                        install_base == "bin"
                    )

                if module_backed:
                    realization_kind = (
                        AndroidDeviceTreeBuildRealizationKind
                        .PREBUILT_MODULE
                    )

                    if (
                        representation.kind
                        is AndroidReconstructionBuildRepresentationKind
                        .NATIVE_LIBRARY
                    ):
                        module_prefix = (
                            "treeforge_native_"
                        )

                    else:
                        module_prefix = (
                            "treeforge_executable_"
                        )

                    module_name = (
                        module_prefix
                        + sha256(
                            representation
                            .representation_id
                            .encode("utf-8")
                        ).hexdigest()[:20]
                    )

                else:
                    realization_kind = (
                        AndroidDeviceTreeBuildRealizationKind
                        .COPY_FILE
                    )
                    module_name = None

                status = (
                    AndroidDeviceTreeBuildRealizationStatus
                    .RESOLVED
                )

                reason = None

            else:
                source_path = None
                module_name = None

                realization_kind = (
                    AndroidDeviceTreeBuildRealizationKind
                    .PREBUILT_MODULE
                )

                status = (
                    AndroidDeviceTreeBuildRealizationStatus
                    .CLOSED
                )

                reason = (
                    "Canonical ELF, Artifact, and Runtime Linking "
                    "evidence prove exact native/executable build "
                    "participation and physical dependencies, but "
                    "the canonical Artifact remains container-owned "
                    "and has no independent Device Tree payload. "
                    "Device Tree therefore must not manufacture a "
                    "standalone proprietary prebuilt module."
                )

            realizations.append(
                AndroidDeviceTreeBuildRealization(
                    realization_id=(
                        "device-tree-realization:"
                        f"{representation.representation_id}"
                    ),
                    kind=realization_kind,
                    status=status,
                    build_representation=representation,
                    source_path=source_path,
                    module_name=module_name,
                    dependency_realization_ids=(
                        dependency_realization_ids
                    ),
                    reason=reason,
                )
            )

        result = tuple(
            sorted(
                realizations,
                key=lambda realization: (
                    realization.realization_id
                ),
            )
        )

        represented_ids = {
            realization.representation_id
            for realization
            in result
        }

        if represented_ids != elf_representation_ids:
            raise ValueError(
                "Device Tree ELF realization coverage mismatch"
            )

        if len(result) != len(represented_ids):
            raise ValueError(
                "Device Tree ELF realizations must cover each "
                "Reconstruction representation exactly once"
            )

        direct_elf_representation_ids = {
            representation_id
            for representation_id
            in elf_representation_ids
            if representation_id
            in physical_projection_by_representation_id
        }

        resolved_elf_representation_ids = {
            realization.representation_id
            for realization
            in result
            if (
                realization.status
                is AndroidDeviceTreeBuildRealizationStatus
                .RESOLVED
            )
        }

        if (
            resolved_elf_representation_ids
            != direct_elf_representation_ids
        ):
            missing = sorted(
                direct_elf_representation_ids
                - resolved_elf_representation_ids
            )

            unexpected = sorted(
                resolved_elf_representation_ids
                - direct_elf_representation_ids
            )

            raise ValueError(
                "Device Tree concrete ELF module coverage mismatch: "
                f"missing={len(missing)}, "
                f"unexpected={len(unexpected)}"
            )

        direct_realizations = tuple(
            realization
            for realization
            in result
            if realization.representation_id
            in direct_elf_representation_ids
        )

        if not all(
            realization.source_path is not None
            and realization.reason is None
            for realization
            in direct_realizations
        ):
            raise ValueError(
                "DIRECT_PARTITION ELF realizations must retain "
                "their exact physical source paths"
            )

        module_backed_direct_realizations = tuple(
            realization
            for realization
            in direct_realizations
            if (
                realization.kind
                is AndroidDeviceTreeBuildRealizationKind
                .PREBUILT_MODULE
            )
        )

        copy_file_direct_realizations = tuple(
            realization
            for realization
            in direct_realizations
            if (
                realization.kind
                is AndroidDeviceTreeBuildRealizationKind
                .COPY_FILE
            )
        )

        if (
            len(module_backed_direct_realizations)
            + len(copy_file_direct_realizations)
            != len(direct_realizations)
        ):
            raise ValueError(
                "DIRECT_PARTITION ELF realizations must use "
                "PREBUILT_MODULE or COPY_FILE"
            )

        if not all(
            realization.module_name is not None
            for realization
            in module_backed_direct_realizations
        ):
            raise ValueError(
                "module-backed DIRECT_PARTITION ELF "
                "realizations require TreeForge module names"
            )

        if any(
            realization.module_name is not None
            for realization
            in copy_file_direct_realizations
        ):
            raise ValueError(
                "COPY_FILE DIRECT_PARTITION ELF realizations "
                "must not manufacture module identities"
            )

        module_names = tuple(
            realization.module_name
            for realization
            in module_backed_direct_realizations
        )

        if len(module_names) != len(
            set(module_names)
        ):
            raise ValueError(
                "TreeForge-generated ELF module identities "
                "must be globally unique"
            )

        container_realizations = tuple(
            realization
            for realization
            in result
            if realization.representation_id
            not in direct_elf_representation_ids
        )

        if any(
            realization.source_path is not None
            or realization.module_name is not None
            or realization.status
            is not AndroidDeviceTreeBuildRealizationStatus.CLOSED
            for realization
            in container_realizations
        ):
            raise ValueError(
                "container-owned ELF realizations must remain "
                "CLOSED without standalone payload/module identity"
            )

        projected_dependency_edge_count = sum(
            len(
                realization.dependency_realization_ids
            )
            for realization
            in result
        )

        expected_dependency_edge_count = sum(
            len(
                representation.dependency_ids
            )
            for representation
            in elf_representations
        )

        if (
            projected_dependency_edge_count
            != expected_dependency_edge_count
        ):
            raise ValueError(
                "Device Tree ELF dependency projection "
                "coverage mismatch"
            )

        return result



class AndroidDeviceTreeJavaBuildRealizationProjector:
    """
    Realize exact Classpath-backed JAVA_LIBRARY participation.

    Reconstruction has already reconciled effective Classpath entries to
    canonical installed JAR Artifacts.

    Preserved-backed Java representations retain the exact Device Tree
    realization already selected by the preserved-artifact projector:

    - DIRECT_PARTITION artifacts remain resolved COPY_FILE realizations;
    - container-resident artifacts remain resolved PRESERVED_ONLY
      realizations.

    Requirement-backed Java representations may become resolved COPY_FILE
    realizations only when Device Tree has an exact DIRECT_PARTITION physical
    payload projection for the same Reconstruction representation and
    canonical Artifact requirement.

    Device Tree does not invent a Java Make/Soong module identity merely
    because the installed artifact is a JAR. The observed installed bytes and
    path are sufficient for exact copy realization, while source-module
    identity and Java build policy remain unproven.

    Classpath membership/order is not converted into physical dependency
    edges here. Only Reconstruction dependency_ids are projected.
    """

    @classmethod
    def project(
        cls,
        reconstruction,
        *,
        existing_realizations: tuple[
            AndroidDeviceTreeBuildRealization,
            ...,
        ],
        physical_payload_projections,
    ) -> tuple[
        AndroidDeviceTreeBuildRealization,
        ...,
    ]:
        from treeforge.android.device_tree.physical_payload_projection import (
            AndroidDeviceTreePhysicalPayloadProjection,
        )
        from treeforge.android.reconstruction.build_system.model import (
            AndroidReconstructionBuildRepresentationKind,
        )
        from treeforge.android.reconstruction.model import (
            AndroidReconstructionResult,
        )

        if not isinstance(
            reconstruction,
            AndroidReconstructionResult,
        ):
            raise TypeError(
                "reconstruction must be an "
                "AndroidReconstructionResult"
            )

        if not isinstance(
            existing_realizations,
            tuple,
        ):
            raise TypeError(
                "existing_realizations must be a tuple"
            )

        if not all(
            isinstance(
                realization,
                AndroidDeviceTreeBuildRealization,
            )
            for realization
            in existing_realizations
        ):
            raise TypeError(
                "existing_realizations must contain only "
                "AndroidDeviceTreeBuildRealization values"
            )

        if not isinstance(
            physical_payload_projections,
            tuple,
        ):
            raise TypeError(
                "physical_payload_projections must be a tuple"
            )

        if not all(
            isinstance(
                projection,
                AndroidDeviceTreePhysicalPayloadProjection,
            )
            for projection
            in physical_payload_projections
        ):
            raise TypeError(
                "physical_payload_projections must contain only "
                "AndroidDeviceTreePhysicalPayloadProjection values"
            )

        java_representations = tuple(
            representation
            for representation
            in reconstruction.artifact_build_representations
            if (
                representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .JAVA_LIBRARY
            )
        )

        java_representation_ids = {
            representation.representation_id
            for representation
            in java_representations
        }

        existing_by_representation_id = {
            realization.representation_id:
            realization
            for realization
            in existing_realizations
        }

        if len(
            existing_by_representation_id
        ) != len(
            existing_realizations
        ):
            raise ValueError(
                "existing Device Tree realizations must preserve "
                "unique Reconstruction representation coverage"
            )

        physical_by_representation_id = {
            projection.representation_id:
            projection
            for projection
            in physical_payload_projections
        }

        if len(
            physical_by_representation_id
        ) != len(
            physical_payload_projections
        ):
            raise ValueError(
                "physical payload projections must preserve "
                "unique Reconstruction representation identity"
            )

        all_representation_ids = {
            representation.representation_id
            for representation
            in reconstruction.artifact_build_representations
        }

        realizations = []

        preserved_backed_count = 0
        requirement_backed_count = 0
        retained_preserved_count = 0
        resolved_requirement_count = 0

        for representation in java_representations:
            if (
                representation.source_content_id is not None
                or representation.source_module_id is not None
            ):
                raise ValueError(
                    "JAVA_LIBRARY realization encountered "
                    "unexpected source-content/source-module payload: "
                    f"{representation.representation_id}"
                )

            missing_dependency_ids = (
                set(
                    representation.dependency_ids
                )
                - all_representation_ids
            )

            if missing_dependency_ids:
                raise ValueError(
                    "JAVA_LIBRARY representation references missing "
                    "Reconstruction dependency identities: "
                    f"{representation.representation_id}, "
                    f"missing={sorted(missing_dependency_ids)!r}"
                )

            dependency_realization_ids = tuple(
                sorted(
                    (
                        "device-tree-realization:"
                        f"{dependency_id}"
                    )
                    for dependency_id
                    in representation.dependency_ids
                )
            )

            if (
                representation.preserved_artifact_id
                is not None
            ):
                preserved_backed_count += 1

                existing = (
                    existing_by_representation_id.get(
                        representation.representation_id
                    )
                )

                if existing is None:
                    raise ValueError(
                        "preserved-backed JAVA_LIBRARY must already "
                        "have its preserved Device Tree realization: "
                        f"{representation.representation_id}"
                    )

                if (
                    existing.build_representation
                    is not representation
                ):
                    raise ValueError(
                        "preserved-backed JAVA_LIBRARY changed exact "
                        "Reconstruction representation identity: "
                        f"{representation.representation_id}"
                    )

                if (
                    existing.kind
                    not in {
                        AndroidDeviceTreeBuildRealizationKind
                        .COPY_FILE,
                        AndroidDeviceTreeBuildRealizationKind
                        .PRESERVED_ONLY,
                    }
                ):
                    raise ValueError(
                        "preserved-backed JAVA_LIBRARY must retain "
                        "COPY_FILE or PRESERVED_ONLY realization: "
                        f"{representation.representation_id}"
                    )

                if (
                    existing.status
                    is not AndroidDeviceTreeBuildRealizationStatus
                    .RESOLVED
                ):
                    raise ValueError(
                        "preserved-backed JAVA_LIBRARY must retain "
                        "a resolved preserved realization: "
                        f"{representation.representation_id}"
                    )

                if (
                    existing.dependency_realization_ids
                    != dependency_realization_ids
                ):
                    if (
                        existing.dependency_realization_ids
                        or dependency_realization_ids
                    ):
                        raise ValueError(
                            "preserved-backed JAVA_LIBRARY dependency "
                            "projection differs from its preserved "
                            "realization: "
                            f"{representation.representation_id}"
                        )

                realizations.append(
                    existing
                )

                retained_preserved_count += 1

                continue

            if (
                representation.canonical_requirement_id
                is None
            ):
                raise ValueError(
                    "JAVA_LIBRARY realization requires exact "
                    "preserved-artifact or canonical-requirement "
                    "payload identity: "
                    f"{representation.representation_id}"
                )

            requirement_backed_count += 1

            if (
                representation.representation_id
                in existing_by_representation_id
            ):
                raise ValueError(
                    "requirement-backed JAVA_LIBRARY unexpectedly "
                    "already has a Device Tree realization: "
                    f"{representation.representation_id}"
                )

            projection = (
                physical_by_representation_id.get(
                    representation.representation_id
                )
            )

            if projection is None:
                raise ValueError(
                    "requirement-backed JAVA_LIBRARY requires an "
                    "exact DIRECT_PARTITION physical payload "
                    "projection: "
                    f"{representation.representation_id}"
                )

            if (
                projection.build_representation
                is not representation
            ):
                raise ValueError(
                    "JAVA_LIBRARY physical payload projection "
                    "changed exact Reconstruction representation "
                    "identity: "
                    f"{representation.representation_id}"
                )

            if (
                projection.requirement_id
                != representation.canonical_requirement_id
            ):
                raise ValueError(
                    "JAVA_LIBRARY physical payload projection "
                    "changed canonical Artifact requirement identity: "
                    f"{representation.representation_id}"
                )

            if (
                projection.installed_partition
                != representation.installed_partition
            ):
                raise ValueError(
                    "JAVA_LIBRARY physical payload projection "
                    "changed installed partition: "
                    f"{representation.representation_id}"
                )

            if (
                projection.installed_android_path
                != representation.installed_android_path
            ):
                raise ValueError(
                    "JAVA_LIBRARY physical payload projection "
                    "changed installed Android path: "
                    f"{representation.representation_id}"
                )

            if not (
                projection.installed_android_path
                .lower()
                .endswith(".jar")
            ):
                raise ValueError(
                    "requirement-backed JAVA_LIBRARY physical "
                    "payload must be an installed JAR: "
                    f"{representation.representation_id}, "
                    f"path={projection.installed_android_path!r}"
                )

            realizations.append(
                AndroidDeviceTreeBuildRealization(
                    realization_id=(
                        "device-tree-realization:"
                        f"{representation.representation_id}"
                    ),
                    kind=(
                        AndroidDeviceTreeBuildRealizationKind
                        .COPY_FILE
                    ),
                    status=(
                        AndroidDeviceTreeBuildRealizationStatus
                        .RESOLVED
                    ),
                    build_representation=representation,
                    source_path=projection.destination,
                    module_name=None,
                    dependency_realization_ids=(
                        dependency_realization_ids
                    ),
                    reason=None,
                )
            )

            resolved_requirement_count += 1

        result = tuple(
            sorted(
                realizations,
                key=lambda realization: (
                    realization.realization_id
                ),
            )
        )

        represented_ids = {
            realization.representation_id
            for realization
            in result
        }

        if represented_ids != java_representation_ids:
            raise ValueError(
                "Device Tree JAVA_LIBRARY realization coverage mismatch"
            )

        if len(result) != len(
            represented_ids
        ):
            raise ValueError(
                "Device Tree JAVA_LIBRARY realizations must cover "
                "each Reconstruction representation exactly once"
            )

        if (
            preserved_backed_count
            + requirement_backed_count
            != len(java_representations)
        ):
            raise ValueError(
                "JAVA_LIBRARY payload classification coverage mismatch"
            )

        if (
            retained_preserved_count
            != preserved_backed_count
        ):
            raise ValueError(
                "preserved-backed JAVA_LIBRARY retention "
                "coverage mismatch"
            )

        if (
            resolved_requirement_count
            != requirement_backed_count
        ):
            raise ValueError(
                "requirement-backed JAVA_LIBRARY physical "
                "realization coverage mismatch"
            )

        projected_dependency_edge_count = sum(
            len(
                realization.dependency_realization_ids
            )
            for realization
            in result
        )

        expected_dependency_edge_count = sum(
            len(
                representation.dependency_ids
            )
            for representation
            in java_representations
        )

        if (
            projected_dependency_edge_count
            != expected_dependency_edge_count
        ):
            raise ValueError(
                "Device Tree JAVA_LIBRARY dependency projection "
                "coverage mismatch"
            )

        return result


class AndroidDeviceTreeApexBuildRealizationProjector:
    """
    Realize canonical APEX build participation.

    Universe and Reconstruction establish canonical APEX identity,
    version, deployment placement, runtime context, and exact
    Extraction container identity.

    Device Tree may select a concrete prebuilt APEX mechanism only
    when its first-class root-runtime APEX payload projection proves
    an independently materializable `.apex` build payload.

    Standalone `.apex` containers use their exact canonical container.

    Standalone factory `.capex` containers are resolved only when
    canonical Extraction lineage has already exposed their exact
    `original_apex`. Device Tree materializes that exact uncompressed
    APEX at a deterministic `.apex` build-source destination while
    retaining the outer `.capex` installed path as canonical
    deployment provenance.

    Nested-runtime APEX containers remain closed/container-owned and
    are never promoted into independent root Device Tree modules.

    Runtime Linking relationships are not flattened into physical
    build dependencies. Only Reconstruction dependency_ids are
    projected.
    """

    @classmethod
    def project(
        cls,
        reconstruction,
        *,
        existing_realizations: tuple[
            AndroidDeviceTreeBuildRealization,
            ...,
        ],
        apex_payload_projections,
    ) -> tuple[
        AndroidDeviceTreeBuildRealization,
        ...,
    ]:
        from treeforge.android.device_tree.apex_payload_projection import (
            AndroidDeviceTreeApexPayloadProjection,
        )
        from treeforge.android.reconstruction.build_system.model import (
            AndroidReconstructionBuildRepresentationKind,
        )
        from treeforge.android.reconstruction.model import (
            AndroidReconstructionResult,
        )

        if not isinstance(
            reconstruction,
            AndroidReconstructionResult,
        ):
            raise TypeError(
                "reconstruction must be an "
                "AndroidReconstructionResult"
            )

        if not isinstance(
            existing_realizations,
            tuple,
        ):
            raise TypeError(
                "existing_realizations must be a tuple"
            )

        if not all(
            isinstance(
                realization,
                AndroidDeviceTreeBuildRealization,
            )
            for realization
            in existing_realizations
        ):
            raise TypeError(
                "existing_realizations must contain only "
                "AndroidDeviceTreeBuildRealization values"
            )

        if not isinstance(
            apex_payload_projections,
            tuple,
        ):
            raise TypeError(
                "apex_payload_projections must be a tuple"
            )

        if not all(
            isinstance(
                projection,
                AndroidDeviceTreeApexPayloadProjection,
            )
            for projection
            in apex_payload_projections
        ):
            raise TypeError(
                "apex_payload_projections contains "
                "an invalid model"
            )

        apex_projection_by_representation_id = {
            projection.representation_id:
            projection
            for projection
            in apex_payload_projections
        }

        if len(
            apex_projection_by_representation_id
        ) != len(
            apex_payload_projections
        ):
            raise ValueError(
                "APEX payload projections must preserve unique "
                "Reconstruction representation identity"
            )

        apex_representations = tuple(
            representation
            for representation
            in reconstruction.artifact_build_representations
            if (
                representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .APEX
            )
        )

        apex_representation_ids = {
            representation.representation_id
            for representation
            in apex_representations
        }

        existing_representation_ids = {
            realization.representation_id
            for realization
            in existing_realizations
        }

        overlap = (
            apex_representation_ids
            & existing_representation_ids
        )

        if overlap:
            raise ValueError(
                "APEX realization population overlaps existing "
                "Device Tree representation coverage: "
                f"{sorted(overlap)!r}"
            )

        unexpected_projection_ids = (
            set(
                apex_projection_by_representation_id
            )
            - apex_representation_ids
        )

        if unexpected_projection_ids:
            raise ValueError(
                "APEX payload projection references non-APEX "
                "Reconstruction representations: "
                f"{sorted(unexpected_projection_ids)!r}"
            )

        all_representation_ids = {
            representation.representation_id
            for representation
            in reconstruction.artifact_build_representations
        }

        realizations = []

        for representation in apex_representations:
            if (
                representation.canonical_requirement_id
                is None
            ):
                raise ValueError(
                    "Device Tree APEX realization requires "
                    "canonical requirement-backed identity: "
                    f"{representation.representation_id}"
                )

            if (
                representation.source_content_id is not None
                or representation.preserved_artifact_id is not None
                or representation.source_module_id is not None
            ):
                raise ValueError(
                    "APEX realization encountered an unexpected "
                    "non-requirement payload identity: "
                    f"{representation.representation_id}"
                )

            if representation.installed_partition is None:
                raise ValueError(
                    "APEX realization requires canonical installed "
                    "partition identity: "
                    f"{representation.representation_id}"
                )

            if representation.installed_android_path is None:
                raise ValueError(
                    "APEX realization requires canonical installed "
                    "Android path identity: "
                    f"{representation.representation_id}"
                )

            missing_dependency_ids = (
                set(representation.dependency_ids)
                - all_representation_ids
            )

            if missing_dependency_ids:
                raise ValueError(
                    "APEX representation references missing "
                    "Reconstruction dependency identities: "
                    f"{representation.representation_id}, "
                    f"missing={sorted(missing_dependency_ids)!r}"
                )

            dependency_realization_ids = tuple(
                sorted(
                    "device-tree-realization:"
                    f"{dependency_id}"
                    for dependency_id
                    in representation.dependency_ids
                )
            )

            projection = (
                apex_projection_by_representation_id.get(
                    representation.representation_id
                )
            )

            if projection is None:
                #
                # Canonically represented, but not independently
                # projectable into the root runtime. This is the
                # nested-runtime/container-owned case.
                #
                source_path = None
                module_name = None

                status = (
                    AndroidDeviceTreeBuildRealizationStatus
                    .CLOSED
                )

                reason = (
                    "Canonical APEX participation is preserved, "
                    "but this APEX is not independently projectable "
                    "into the root Device Tree runtime and remains "
                    "owned by its enclosing container."
                )

            else:
                if (
                    projection.build_representation
                    is not representation
                ):
                    raise ValueError(
                        "APEX payload projection changed exact "
                        "Reconstruction representation identity: "
                        f"{representation.representation_id}"
                    )

                if (
                    projection.requirement_id
                    != representation.canonical_requirement_id
                ):
                    raise ValueError(
                        "APEX payload projection changed canonical "
                        "requirement identity: "
                        f"{representation.representation_id}"
                    )

                if (
                    projection.installed_partition
                    != representation.installed_partition
                ):
                    raise ValueError(
                        "APEX payload projection changed canonical "
                        "installed partition: "
                        f"{representation.representation_id}"
                    )

                if (
                    projection.installed_android_path
                    != representation.installed_android_path
                ):
                    raise ValueError(
                        "APEX payload projection changed canonical "
                        "installed Android path: "
                        f"{representation.representation_id}"
                    )

                source_path = projection.destination

                #
                # Root-runtime payload projection has already separated
                # canonical installed-container provenance from the exact
                # build-consumable APEX payload.
                #
                # Both direct .apex and canonical CAPEX original_apex
                # projections must therefore terminate in .apex here.
                #
                if (
                    projection.destination.suffix.lower()
                    != ".apex"
                ):
                    raise ValueError(
                        "root-runtime APEX build payload must use "
                        "a .apex Device Tree source destination: "
                        f"{projection.destination!s}"
                    )

                status = (
                    AndroidDeviceTreeBuildRealizationStatus
                    .RESOLVED
                )

                module_name = (
                    "treeforge_apex_"
                    + sha256(
                        representation
                        .representation_id
                        .encode("utf-8")
                    ).hexdigest()[:20]
                )

                reason = None

            realizations.append(
                AndroidDeviceTreeBuildRealization(
                    realization_id=(
                        "device-tree-realization:"
                        f"{representation.representation_id}"
                    ),
                    kind=(
                        AndroidDeviceTreeBuildRealizationKind
                        .APEX_MODULE
                    ),
                    status=status,
                    build_representation=representation,
                    source_path=source_path,
                    module_name=module_name,
                    dependency_realization_ids=(
                        dependency_realization_ids
                    ),
                    reason=reason,
                )
            )

        result = tuple(
            sorted(
                realizations,
                key=lambda realization: (
                    realization.realization_id
                ),
            )
        )

        represented_ids = {
            realization.representation_id
            for realization
            in result
        }

        if represented_ids != apex_representation_ids:
            raise ValueError(
                "Device Tree APEX realization coverage mismatch"
            )

        if len(result) != len(represented_ids):
            raise ValueError(
                "Device Tree APEX realizations must cover each "
                "Reconstruction representation exactly once"
            )

        #
        # Every first-class APEX payload projection is independently
        # projectable into the root Device Tree runtime.
        #
        # Direct factory .apex containers project their exact container.
        # Factory .capex containers project the exact canonical
        # Extraction `original_apex` at a deterministic .apex build
        # destination. Nested/container-owned APEXes have no payload
        # projection and therefore remain CLOSED outside this set.
        #
        expected_resolved_ids = {
            projection.representation_id
            for projection
            in apex_payload_projections
        }

        resolved_ids = {
            realization.representation_id
            for realization
            in result
            if (
                realization.status
                is AndroidDeviceTreeBuildRealizationStatus
                .RESOLVED
            )
        }

        if resolved_ids != expected_resolved_ids:
            raise ValueError(
                "Device Tree concrete prebuilt APEX coverage "
                "mismatch"
            )

        resolved_realizations = tuple(
            realization
            for realization
            in result
            if (
                realization.status
                is AndroidDeviceTreeBuildRealizationStatus
                .RESOLVED
            )
        )

        if not all(
            realization.source_path is not None
            and realization.module_name is not None
            and realization.reason is None
            for realization
            in resolved_realizations
        ):
            raise ValueError(
                "resolved APEX realizations require exact payload "
                "paths and deterministic TreeForge module names"
            )

        module_names = tuple(
            realization.module_name
            for realization
            in resolved_realizations
        )

        if len(module_names) != len(
            set(module_names)
        ):
            raise ValueError(
                "TreeForge-generated APEX module identities "
                "must be globally unique"
            )

        projected_dependency_edge_count = sum(
            len(realization.dependency_realization_ids)
            for realization
            in result
        )

        expected_dependency_edge_count = sum(
            len(representation.dependency_ids)
            for representation
            in apex_representations
        )

        if (
            projected_dependency_edge_count
            != expected_dependency_edge_count
        ):
            raise ValueError(
                "Device Tree APEX dependency projection "
                "coverage mismatch"
            )

        return result


class AndroidDeviceTreeKernelModuleBuildRealizationProjector:
    """
    Realize canonical kernel modules and modules.* configuration files.

    Exact DIRECT_PARTITION DLKM .ko payloads become resolved KERNEL_MODULE
    realizations backed by their first-class physical payload projection.

    BOOT_FILESYSTEM / otherwise non-direct module requirements remain closed;
    Device Tree must not invent standalone source payloads for container-owned
    modules.

    Exact DIRECT_PARTITION modules.load and modules.blocklist files become
    resolved SOURCE_CONFIG inputs for BoardConfig rendering.

    modules.dep, modules.alias, and modules.softdep are closed build
    representations because Android's DLKM machinery regenerates that depmod
    metadata from the exact .ko population.

    Reconstruction dependency_ids remain authoritative semantic dependency
    edges and are preserved mechanically without being re-resolved here.
    """

    @classmethod
    def project(
        cls,
        reconstruction,
        *,
        existing_realizations: tuple[
            AndroidDeviceTreeBuildRealization,
            ...,
        ],
        physical_payload_projections,
        vendor_kernel_ramdisk_projections=(),
    ) -> tuple[
        AndroidDeviceTreeBuildRealization,
        ...,
    ]:
        from treeforge.android.device_tree.physical_payload_projection import (
            AndroidDeviceTreePhysicalPayloadProjection,
        )
        from treeforge.android.reconstruction.build_system.model import (
            AndroidReconstructionBuildRepresentationKind,
        )
        from treeforge.android.reconstruction.model import (
            AndroidReconstructionResult,
        )

        if not isinstance(
            reconstruction,
            AndroidReconstructionResult,
        ):
            raise TypeError(
                "reconstruction must be an "
                "AndroidReconstructionResult"
            )

        if not isinstance(
            existing_realizations,
            tuple,
        ):
            raise TypeError(
                "existing_realizations must be a tuple"
            )

        if not all(
            isinstance(
                realization,
                AndroidDeviceTreeBuildRealization,
            )
            for realization
            in existing_realizations
        ):
            raise TypeError(
                "existing_realizations must contain only "
                "AndroidDeviceTreeBuildRealization values"
            )

        if not isinstance(
            physical_payload_projections,
            tuple,
        ):
            raise TypeError(
                "physical_payload_projections must be a tuple"
            )

        if not all(
            isinstance(
                projection,
                AndroidDeviceTreePhysicalPayloadProjection,
            )
            for projection
            in physical_payload_projections
        ):
            raise TypeError(
                "physical_payload_projections contains "
                "an invalid model"
            )

        physical_by_representation_id = {
            projection.representation_id:
            projection
            for projection
            in physical_payload_projections
        }

        from treeforge.android.device_tree.vendor_kernel_ramdisk import (
            AndroidDeviceTreeVendorKernelRamdiskModuleProjection,
        )

        if not isinstance(
            vendor_kernel_ramdisk_projections,
            tuple,
        ):
            raise TypeError(
                "vendor_kernel_ramdisk_projections must be a tuple"
            )

        if not all(
            isinstance(
                item,
                AndroidDeviceTreeVendorKernelRamdiskModuleProjection,
            )
            for item
            in vendor_kernel_ramdisk_projections
        ):
            raise TypeError(
                "vendor_kernel_ramdisk_projections contains "
                "an invalid model"
            )

        vendor_kernel_ramdisk_by_representation_id = {
            item.representation_id:
            item
            for item
            in vendor_kernel_ramdisk_projections
        }

        if len(
            vendor_kernel_ramdisk_by_representation_id
        ) != len(
            vendor_kernel_ramdisk_projections
        ):
            raise ValueError(
                "vendor kernel ramdisk projection representation "
                "identities must be unique"
            )

        if len(
            physical_by_representation_id
        ) != len(
            physical_payload_projections
        ):
            raise ValueError(
                "physical payload projection identities "
                "must be unique"
            )

        kernel_representations = tuple(
            representation
            for representation
            in reconstruction.artifact_build_representations
            if (
                representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .KERNEL_MODULE
            )
        )

        kernel_config_representations = tuple(
            representation
            for representation
            in reconstruction.artifact_build_representations
            if (
                representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .SOURCE_CONFIG
                and representation.source_identity.startswith(
                    "kernel-module-config:"
                )
            )
        )

        target_representations = (
            *kernel_representations,
            *kernel_config_representations,
        )

        target_representation_ids = {
            representation.representation_id
            for representation
            in target_representations
        }

        existing_by_representation_id = {
            realization.representation_id:
            realization
            for realization
            in existing_realizations
        }

        if len(
            existing_by_representation_id
        ) != len(
            existing_realizations
        ):
            raise ValueError(
                "existing Device Tree realizations must preserve "
                "unique Reconstruction representation coverage"
            )

        #
        # KERNEL_MODULE Artifact requirements are canonically PRESERVE
        # obligations. The generic preserved projector therefore establishes
        # their first Device Tree realization before this family-specific
        # projector runs.
        #
        # This projector specializes that same canonical representation; it
        # does not introduce a second payload identity. Only generic preserved
        # COPY_FILE/PRESERVED_ONLY coverage may be superseded here.
        #
        for representation in target_representations:
            existing = existing_by_representation_id.get(
                representation.representation_id
            )

            if existing is None:
                continue

            if existing.build_representation is not representation:
                raise ValueError(
                    "kernel specialization changed exact "
                    "Reconstruction representation identity: "
                    f"{representation.representation_id}"
                )

            if (
                representation.kind
                is not AndroidReconstructionBuildRepresentationKind
                .KERNEL_MODULE
            ):
                raise ValueError(
                    "kernel config realization unexpectedly overlaps "
                    "existing Device Tree representation coverage: "
                    f"{representation.representation_id}"
                )

            if existing.kind not in {
                AndroidDeviceTreeBuildRealizationKind.COPY_FILE,
                AndroidDeviceTreeBuildRealizationKind.PRESERVED_ONLY,
            }:
                raise ValueError(
                    "kernel specialization may supersede only generic "
                    "preserved COPY_FILE/PRESERVED_ONLY coverage: "
                    f"{representation.representation_id}, "
                    f"kind={existing.kind.value}"
                )

            if (
                existing.status
                is not AndroidDeviceTreeBuildRealizationStatus.RESOLVED
            ):
                raise ValueError(
                    "kernel specialization requires resolved generic "
                    "preserved coverage: "
                    f"{representation.representation_id}"
                )

        all_representation_ids = {
            representation.representation_id
            for representation
            in reconstruction.artifact_build_representations
        }

        realizations = []

        resolved_direct_modules = 0
        resolved_vendor_kernel_ramdisk_modules = 0
        partial_non_direct_modules = 0

        resolved_direct_configs = 0
        generated_metadata_configs = 0
        partial_non_direct_configs = 0

        for representation in target_representations:
            if (
                representation.source_content_id is not None
                or representation.source_module_id is not None
            ):
                raise ValueError(
                    "kernel realization encountered an unexpected "
                    "source-content/source-module payload identity: "
                    f"{representation.representation_id}"
                )

            artifact_requirement_id = (
                representation.preserved_artifact_id
                or representation.canonical_requirement_id
            )

            if artifact_requirement_id is None:
                raise ValueError(
                    "kernel-module/config realization requires "
                    "exact preserved-artifact or canonical-requirement "
                    "identity: "
                    f"{representation.representation_id}"
                )

            if (
                representation.preserved_artifact_id is not None
                and
                representation.canonical_requirement_id is not None
                and
                representation.preserved_artifact_id
                != representation.canonical_requirement_id
            ):
                raise ValueError(
                    "kernel-module/config realization has conflicting "
                    "canonical Artifact identities: "
                    f"{representation.representation_id}"
                )

            if representation.installed_partition is None:
                raise ValueError(
                    "kernel-module/config realization requires "
                    "installed partition identity"
                )

            if representation.installed_android_path is None:
                raise ValueError(
                    "kernel-module/config realization requires "
                    "installed Android path identity"
                )

            missing_dependency_ids = (
                set(representation.dependency_ids)
                - all_representation_ids
            )

            if missing_dependency_ids:
                raise ValueError(
                    "kernel-module/config representation references "
                    "missing Reconstruction dependencies: "
                    f"{representation.representation_id}, "
                    f"missing={sorted(missing_dependency_ids)!r}"
                )

            dependency_realization_ids = tuple(
                sorted(
                    "device-tree-realization:"
                    f"{dependency_id}"
                    for dependency_id
                    in representation.dependency_ids
                )
            )

            projection = (
                physical_by_representation_id.get(
                    representation.representation_id
                )
            )

            if projection is not None:
                if (
                    projection.build_representation
                    is not representation
                ):
                    raise ValueError(
                        "kernel physical payload projection changed "
                        "exact Reconstruction representation identity"
                    )

                if (
                    projection.requirement_id
                    != artifact_requirement_id
                ):
                    raise ValueError(
                        "kernel physical payload projection changed "
                        "canonical Artifact identity"
                    )

                if (
                    projection.installed_partition
                    != representation.installed_partition
                    or
                    projection.installed_android_path
                    != representation.installed_android_path
                ):
                    raise ValueError(
                        "kernel physical payload projection changed "
                        "canonical installed identity"
                    )

            if (
                representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .KERNEL_MODULE
            ):
                realization_kind = (
                    AndroidDeviceTreeBuildRealizationKind
                    .KERNEL_MODULE
                )

                if not (
                    representation.installed_android_path
                    .lower()
                    .endswith(".ko")
                ):
                    raise ValueError(
                        "KERNEL_MODULE payload must be an installed "
                        ".ko file"
                    )

                existing = existing_by_representation_id.get(
                    representation.representation_id
                )

                if (
                    representation.installed_partition
                    in {
                        "system_dlkm",
                        "vendor_dlkm",
                    }
                ):
                    if projection is not None:
                        source_path = projection.destination

                    elif (
                        representation.preserved_artifact_id
                        is not None
                    ):
                        if existing is None:
                            raise ValueError(
                                "preserved-backed direct KERNEL_MODULE "
                                "must already have a preserved Device "
                                "Tree realization: "
                                f"{representation.representation_id}"
                            )

                        if (
                            existing.status
                            is not
                            AndroidDeviceTreeBuildRealizationStatus
                            .RESOLVED
                        ):
                            raise ValueError(
                                "preserved-backed direct KERNEL_MODULE "
                                "requires resolved preserved coverage: "
                                f"{representation.representation_id}"
                            )

                        if existing.source_path is None:
                            raise ValueError(
                                "preserved-backed direct KERNEL_MODULE "
                                "requires an exact preserved source_path: "
                                f"{representation.representation_id}"
                            )

                        source_path = existing.source_path

                    else:
                        raise ValueError(
                            "direct KERNEL_MODULE has neither an exact "
                            "physical projection nor preserved payload: "
                            f"{representation.representation_id}"
                        )

                    status = (
                        AndroidDeviceTreeBuildRealizationStatus
                        .RESOLVED
                    )

                    reason = None
                    resolved_direct_modules += 1

                elif (
                    representation.installed_partition
                    == "vendor_kernel_boot"
                ):
                    vendor_kernel_projection = (
                        vendor_kernel_ramdisk_by_representation_id.get(
                            representation.representation_id
                        )
                    )

                    if vendor_kernel_projection is None:
                        raise ValueError(
                            "vendor_kernel_boot KERNEL_MODULE requires "
                            "dedicated vendor kernel ramdisk projection: "
                            f"{representation.representation_id}"
                        )

                    if (
                        vendor_kernel_projection.build_representation
                        is not representation
                    ):
                        raise ValueError(
                            "vendor kernel ramdisk specialization changed "
                            "exact Reconstruction representation identity"
                        )

                    if (
                        vendor_kernel_projection.artifact_id
                        != artifact_requirement_id
                    ):
                        raise ValueError(
                            "vendor kernel ramdisk specialization changed "
                            "canonical Artifact identity"
                        )

                    status = (
                        AndroidDeviceTreeBuildRealizationStatus
                        .RESOLVED
                    )

                    source_path = (
                        vendor_kernel_projection.destination
                    )

                    reason = None
                    resolved_vendor_kernel_ramdisk_modules += 1

                else:
                    status = (
                        AndroidDeviceTreeBuildRealizationStatus
                        .CLOSED
                    )

                    source_path = None

                    reason = (
                        "Canonical kernel-module evidence proves "
                        "installed container participation and "
                        "modules.dep dependencies, but this module "
                        "belongs to a non-direct/container-owned "
                        "deployment with no supported Device Tree "
                        "build mechanism."
                    )

                    partial_non_direct_modules += 1

            else:
                realization_kind = (
                    AndroidDeviceTreeBuildRealizationKind
                    .SOURCE_CONFIG
                )

                if representation.dependency_ids:
                    raise ValueError(
                        "kernel modules.* SOURCE_CONFIG "
                        "unexpectedly carries physical dependencies"
                    )

                if projection is None:
                    status = (
                        AndroidDeviceTreeBuildRealizationStatus
                        .CLOSED
                    )

                    source_path = None

                    reason = (
                        "Canonical kernel-module configuration "
                        "belongs to a non-direct/container-owned "
                        "deployment. Device Tree does not invent "
                        "an independent source file."
                    )

                    partial_non_direct_configs += 1

                else:
                    name = (
                        PurePosixPath(
                            representation.installed_android_path
                        ).name
                    )

                    if name in {
                        "modules.load",
                        "modules.blocklist",
                    }:
                        if (
                            representation.installed_partition
                            not in {
                                "system_dlkm",
                                "vendor_dlkm",
                            }
                        ):
                            raise ValueError(
                                "direct kernel BoardConfig input "
                                "belongs to unsupported partition"
                            )

                        status = (
                            AndroidDeviceTreeBuildRealizationStatus
                            .RESOLVED
                        )

                        source_path = projection.destination

                        reason = None

                        resolved_direct_configs += 1

                    elif name in {
                        "modules.dep",
                        "modules.alias",
                        "modules.softdep",
                    }:
                        status = (
                            AndroidDeviceTreeBuildRealizationStatus
                            .CLOSED
                        )

                        source_path = None

                        reason = (
                            "Canonical factory depmod metadata is "
                            "preserved as evidence, but Android's "
                            "DLKM build machinery regenerates this "
                            "modules.* output from the exact .ko "
                            "population rather than consuming it as "
                            "a BoardConfig source input."
                        )

                        generated_metadata_configs += 1

                    else:
                        raise ValueError(
                            "unsupported canonical kernel "
                            "modules.* configuration filename: "
                            f"{name!r}"
                        )

            realizations.append(
                AndroidDeviceTreeBuildRealization(
                    realization_id=(
                        "device-tree-realization:"
                        f"{representation.representation_id}"
                    ),
                    kind=realization_kind,
                    status=status,
                    build_representation=representation,
                    source_path=source_path,
                    module_name=None,
                    dependency_realization_ids=(
                        dependency_realization_ids
                    ),
                    reason=reason,
                )
            )

        result = tuple(
            sorted(
                realizations,
                key=lambda realization: (
                    realization.realization_id
                ),
            )
        )

        represented_ids = {
            realization.representation_id
            for realization
            in result
        }

        if represented_ids != target_representation_ids:
            raise ValueError(
                "Device Tree kernel-module realization "
                "coverage mismatch"
            )

        if len(result) != len(represented_ids):
            raise ValueError(
                "Device Tree kernel realizations must cover "
                "each Reconstruction representation exactly once"
            )

        kernel_realizations = tuple(
            realization
            for realization
            in result
            if (
                realization.build_representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .KERNEL_MODULE
            )
        )

        config_realizations = tuple(
            realization
            for realization
            in result
            if (
                realization.build_representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .SOURCE_CONFIG
            )
        )

        if len(kernel_realizations) != len(
            kernel_representations
        ):
            raise ValueError(
                "Device Tree KERNEL_MODULE coverage mismatch"
            )

        if len(config_realizations) != len(
            kernel_config_representations
        ):
            raise ValueError(
                "Device Tree kernel modules.* SOURCE_CONFIG "
                "coverage mismatch"
            )

        if (
            resolved_direct_modules
            + resolved_vendor_kernel_ramdisk_modules
            + partial_non_direct_modules
            != len(kernel_representations)
        ):
            raise ValueError(
                "kernel module deployment classification "
                "coverage mismatch"
            )

        if (
            resolved_direct_configs
            + generated_metadata_configs
            + partial_non_direct_configs
            != len(kernel_config_representations)
        ):
            raise ValueError(
                "kernel config mechanism classification "
                "coverage mismatch"
            )

        projected_kernel_dependency_edges = sum(
            len(realization.dependency_realization_ids)
            for realization
            in kernel_realizations
        )

        expected_kernel_dependency_edges = sum(
            len(representation.dependency_ids)
            for representation
            in kernel_representations
        )

        if (
            projected_kernel_dependency_edges
            != expected_kernel_dependency_edges
        ):
            raise ValueError(
                "Device Tree kernel-module dependency "
                "projection coverage mismatch"
            )

        return result

class AndroidDeviceTreePolicyBuildRealizationProjector:
    """
    Upgrade already-materialized VINTF and SELinux generated sources into
    family-specific Device Tree build realizations.

    Reconstruction already establishes exact source content for both
    families, and Device Tree source projection already chooses a concrete
    source-tree destination and materializes those bytes.

    The remaining downstream uncertainty is build integration:

    - VINTF documents still require the appropriate Android build-variable
      integration for their canonical role;
    - SELinux policy sources still require the appropriate policy-directory
      and build integration.

    This projector does not invent those Make/Soong/BoardConfig statements.
    It preserves the exact source path while marking the stronger
    family-specific realization PARTIAL until concrete renderers own that
    syntax.
    """

    @classmethod
    def project(
        cls,
        reconstruction,
        *,
        existing_realizations: tuple[
            AndroidDeviceTreeBuildRealization,
            ...,
        ],
    ) -> tuple[
        AndroidDeviceTreeBuildRealization,
        ...,
    ]:
        from treeforge.android.reconstruction.build_system.model import (
            AndroidReconstructionBuildRepresentationKind,
        )
        from treeforge.android.reconstruction.model import (
            AndroidReconstructionResult,
        )

        if not isinstance(
            reconstruction,
            AndroidReconstructionResult,
        ):
            raise TypeError(
                "reconstruction must be an "
                "AndroidReconstructionResult"
            )

        if not isinstance(
            existing_realizations,
            tuple,
        ):
            raise TypeError(
                "existing_realizations must be a tuple"
            )

        if not all(
            isinstance(
                realization,
                AndroidDeviceTreeBuildRealization,
            )
            for realization
            in existing_realizations
        ):
            raise TypeError(
                "existing_realizations must contain only "
                "AndroidDeviceTreeBuildRealization values"
            )

        target_kinds = {
            AndroidReconstructionBuildRepresentationKind
            .VINTF_DOCUMENT,
            AndroidReconstructionBuildRepresentationKind
            .SELINUX_POLICY,
            AndroidReconstructionBuildRepresentationKind
            .SELINUX_RUNTIME_OUTPUT,
        }

        target_representations = tuple(
            representation
            for representation
            in reconstruction.artifact_build_representations
            if representation.kind in target_kinds
        )

        target_representation_ids = {
            representation.representation_id
            for representation
            in target_representations
        }

        existing_by_representation_id = {
            realization.representation_id:
            realization
            for realization
            in existing_realizations
        }

        if len(
            existing_by_representation_id
        ) != len(
            existing_realizations
        ):
            raise ValueError(
                "existing Device Tree realizations must preserve "
                "unique Reconstruction representation coverage"
            )

        vintf_source_by_content_id = {}

        vintf_representation_by_id = {
            item.representation_id: item
            for item
            in reconstruction.vintf_document_representations
        }

        for content in reconstruction.vintf_source_contents:
            source_representation = (
                vintf_representation_by_id.get(
                    content.representation_id
                )
            )

            if source_representation is None:
                raise ValueError(
                    "VINTF source content has no matching "
                    "Reconstruction representation: "
                    f"{content.content_id}"
                )

            vintf_source_by_content_id[
                content.content_id
            ] = source_representation

        selinux_source_by_content_id = {}

        selinux_representation_by_id = {
            item.representation_id: item
            for item in reconstruction.selinux_source_representations
        }

        for content in reconstruction.selinux_source_contents:
            source_representation = (
                selinux_representation_by_id.get(
                    content.representation_id
                )
            )

            if source_representation is None:
                raise ValueError(
                    "SELinux source content has no matching "
                    "Reconstruction representation: "
                    f"{content.content_id}"
                )

            selinux_source_by_content_id[
                content.content_id
            ] = source_representation

        upgraded = []

        for representation in target_representations:
            if representation.source_content_id is None:
                raise ValueError(
                    "VINTF/SELinux Device Tree integration requires "
                    "exact source-content-backed Reconstruction identity: "
                    f"{representation.representation_id}"
                )

            if (
                representation.preserved_artifact_id is not None
                or representation.source_module_id is not None
                or representation.canonical_requirement_id is not None
            ):
                raise ValueError(
                    "VINTF/SELinux source realization must have only "
                    "source_content_id payload identity: "
                    f"{representation.representation_id}"
                )

            existing = (
                existing_by_representation_id.get(
                    representation.representation_id
                )
            )

            if existing is None:
                raise ValueError(
                    "VINTF/SELinux representation must already have "
                    "a source-backed Device Tree realization: "
                    f"{representation.representation_id}"
                )

            if (
                existing.build_representation
                is not representation
            ):
                raise ValueError(
                    "VINTF/SELinux upgrade changed exact "
                    "Reconstruction representation identity"
                )

            if (
                existing.kind
                is not AndroidDeviceTreeBuildRealizationKind
                .GENERATED_SOURCE
            ):
                raise ValueError(
                    "VINTF/SELinux integration must upgrade from "
                    "GENERATED_SOURCE: "
                    f"{representation.representation_id}"
                )

            if existing.source_path is None:
                raise ValueError(
                    "VINTF/SELinux source-backed realization must "
                    "already preserve a Device Tree source path: "
                    f"{representation.representation_id}"
                )

            if representation.dependency_ids:
                raise ValueError(
                    "VINTF/SELinux source build representation "
                    "unexpectedly carries physical dependencies: "
                    f"{representation.representation_id}"
                )

            closed_without_independent_build_object = False

            if (
                representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .VINTF_DOCUMENT
            ):
                realization_kind = (
                    AndroidDeviceTreeBuildRealizationKind
                    .VINTF_DOCUMENT
                )

                vintf_source = (
                    vintf_source_by_content_id.get(
                        representation.source_content_id
                    )
                )

                if vintf_source is None:
                    raise ValueError(
                        "VINTF build representation has no "
                        "matching canonical VINTF source "
                        "representation: "
                        f"{representation.representation_id}"
                    )

                filesystem_source = (
                    vintf_source
                    .requirement
                    .source
                    .filesystem_source
                )

                source_name = getattr(
                    filesystem_source,
                    "source_name",
                    None,
                )

                if (
                    not isinstance(source_name, str)
                    or not source_name
                ):
                    raise ValueError(
                        "VINTF source has no canonical "
                        "filesystem source identity: "
                        f"{representation.representation_id}"
                    )

                android_path = (
                    vintf_source.android_path
                )

                if android_path is None:
                    reason = (
                        "Exact canonical VINTF XML is preserved, "
                        "but no canonical Android-visible path is "
                        "available for concrete build integration."
                    )
                    module_name = None
                else:
                    parts = tuple(
                        android_path.parts
                    )

                    is_base_manifest = (
                        len(parts) >= 3
                        and parts[-3:] == (
                            "etc",
                            "vintf",
                            "manifest.xml",
                        )
                    )

                    is_base_matrix = (
                        len(parts) >= 3
                        and parts[-3:] == (
                            "etc",
                            "vintf",
                            "compatibility_matrix.xml",
                        )
                    )

                    document_kind = getattr(
                        vintf_source.document_kind,
                        "value",
                        None,
                    )

                    document_side = getattr(
                        vintf_source.document_side,
                        "value",
                        None,
                    )

                    is_device_framework_matrix = (
                        document_kind
                        == "compatibility-matrix"
                        and document_side == "framework"
                        and len(parts) >= 3
                        and parts[-3:] == (
                            "etc",
                            "vintf",
                            "compatibility_matrix.device.xml",
                        )
                    )

                    is_system_ext_framework_base_manifest = (
                        source_name == "system_ext"
                        and document_kind == "manifest"
                        and document_side == "framework"
                        and is_base_manifest
                    )

                    is_manifest_fragment = (
                        len(parts) >= 4
                        and parts[-3:-1] == (
                            "vintf",
                            "manifest",
                        )
                        and parts[-1].endswith(
                            ".xml"
                        )
                    )

                    concrete_base = (
                        (
                            source_name == "vendor"
                            and (
                                is_base_manifest
                                or is_base_matrix
                            )
                        )
                        or (
                            source_name == "product"
                            and is_base_matrix
                        )
                        or is_device_framework_matrix
                    )

                    concrete_fragment = (
                        source_name
                        in {
                            "vendor",
                            "system_ext",
                            "vendor_boot",
                        }
                        and is_manifest_fragment
                    )

                    if concrete_base:
                        reason = None
                        module_name = None

                    elif concrete_fragment:
                        reason = None
                        digest = sha256(
                            representation
                            .representation_id
                            .encode("utf-8")
                        ).hexdigest()[:12]

                        module_name = (
                            "treeforge_vintf_fragment_"
                            f"{digest}"
                        )

                    elif (
                        source_name
                        in {
                            "system",
                            "system_a",
                        }
                        or (
                            is_system_ext_framework_base_manifest
                        )
                    ):
                        closed_without_independent_build_object = True

                        reason = (
                            "Exact canonical framework-side VINTF "
                            "document is preserved as factory evidence, "
                            "but its physical source belongs to the "
                            "platform/system VINTF population. Device "
                            "Tree does not duplicate platform-owned "
                            "framework VINTF outputs."
                        )
                        module_name = None

                    elif source_name.startswith(
                        "apex:"
                    ):
                        closed_without_independent_build_object = True

                        reason = (
                            "Exact canonical VINTF document is "
                            "container/APEX-owned and remains attached "
                            "to that container provenance. Device Tree "
                            "does not independently install it."
                        )
                        module_name = None

                    else:
                        reason = (
                            "Exact canonical VINTF XML, semantic role, "
                            "filesystem provenance, and Android path are "
                            "preserved, but no generic concrete Android "
                            "build realization has yet been proven for "
                            f"source class {source_name!r}."
                        )
                        module_name = None

            elif (
                representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .SELINUX_POLICY
            ):
                realization_kind = (
                    AndroidDeviceTreeBuildRealizationKind
                    .SELINUX_POLICY
                )

                reason = (
                    "Exact reconstructed SELinux policy-source content and "
                    "Device Tree source placement are resolved, but the "
                    "required SELinux policy-directory/build integration "
                    "has not yet been rendered into concrete Android "
                    "build syntax."
                )

            else:
                selinux_source = (
                    selinux_source_by_content_id.get(
                        representation.source_content_id
                    )
                )

                if selinux_source is None:
                    raise ValueError(
                        "SELinux runtime-output build representation "
                        "has no matching canonical SELinux source "
                        "representation: "
                        f"{representation.representation_id}"
                    )

                source_kind_value = (
                    selinux_source.source_kind.value
                )

                android_path = (
                    selinux_source.android_path
                )

                generic_vendor_source_kinds = {
                    "file_contexts",
                    "property_contexts",
                    "service_contexts",
                    "hwservice_contexts",
                    "vndservice_contexts",
                    "keystore2_key_contexts",
                }

                generic_source_equivalent = (
                    android_path is not None
                    and android_path.as_posix().startswith(
                        "/vendor/etc/selinux/"
                    )
                    and (
                        source_kind_value
                        in generic_vendor_source_kinds
                        or (
                            source_kind_value
                            == "other_text"
                            and android_path.name
                            == "selinux_denial_metadata"
                        )
                    )
                )

                if generic_source_equivalent:
                    realization_kind = (
                        AndroidDeviceTreeBuildRealizationKind
                        .SELINUX_POLICY
                    )

                    reason = None
                else:
                    realization_kind = (
                        AndroidDeviceTreeBuildRealizationKind
                        .SELINUX_RUNTIME_OUTPUT
                    )

                    reason = (
                        "Exact canonical SELinux runtime/build output "
                        "and Device Tree evidence placement are "
                        "preserved. No generic source-equivalent Android "
                        "build realization has yet been proven for this "
                        "specific runtime output; the item remains "
                        "available for later disposition analysis."
                    )

            upgraded.append(
                AndroidDeviceTreeBuildRealization(
                    realization_id=existing.realization_id,
                    kind=realization_kind,
                    status=(
                        AndroidDeviceTreeBuildRealizationStatus
                        .CLOSED
                        if (
                            closed_without_independent_build_object
                        )
                        else (
                            AndroidDeviceTreeBuildRealizationStatus
                            .RESOLVED
                            if reason is None
                            else AndroidDeviceTreeBuildRealizationStatus
                            .PARTIAL
                        )
                    ),
                    build_representation=representation,
                    source_path=existing.source_path,
                    module_name=(
                        module_name
                        if (
                            representation.kind
                            is AndroidReconstructionBuildRepresentationKind
                            .VINTF_DOCUMENT
                        )
                        else None
                    ),
                    dependency_realization_ids=(),
                    reason=reason,
                )
            )

        result = tuple(
            sorted(
                upgraded,
                key=lambda realization: (
                    realization.realization_id
                ),
            )
        )

        represented_ids = {
            realization.representation_id
            for realization
            in result
        }

        if represented_ids != target_representation_ids:
            raise ValueError(
                "Device Tree VINTF/SELinux realization "
                "coverage mismatch"
            )

        if len(result) != len(represented_ids):
            raise ValueError(
                "Device Tree VINTF/SELinux integrations must cover "
                "each Reconstruction representation exactly once"
            )

        vintf_count = sum(
            realization.kind
            is AndroidDeviceTreeBuildRealizationKind
            .VINTF_DOCUMENT
            for realization
            in result
        )

        expected_vintf_count = sum(
            representation.kind
            is AndroidReconstructionBuildRepresentationKind
            .VINTF_DOCUMENT
            for representation
            in target_representations
        )

        if vintf_count != expected_vintf_count:
            raise ValueError(
                "Device Tree VINTF integration coverage mismatch"
            )

        selinux_count = sum(
            realization.kind
            in {
                AndroidDeviceTreeBuildRealizationKind
                .SELINUX_POLICY,
                AndroidDeviceTreeBuildRealizationKind
                .SELINUX_RUNTIME_OUTPUT,
            }
            for realization
            in result
        )

        expected_selinux_count = sum(
            representation.kind
            in {
                AndroidReconstructionBuildRepresentationKind
                .SELINUX_POLICY,
                AndroidReconstructionBuildRepresentationKind
                .SELINUX_RUNTIME_OUTPUT,
            }
            for representation
            in target_representations
        )

        if selinux_count != expected_selinux_count:
            raise ValueError(
                "Device Tree SELinux integration coverage mismatch"
            )

        return result



class AndroidDeviceTreeBoardBuildRealizationProjector:
    """
    Realize canonical boot, DTBO, and VBMeta participation as pending
    board/image configuration.

    Reconstruction already establishes exact canonical participation for:
    - boot/init_boot/vendor_boot images;
    - DTBO population entries;
    - VBMeta partition images and canonical AVB evidence.

    Device Tree owns eventual BoardConfig/product/image-generation syntax,
    but this projector does not invent that syntax prematurely.

    DTBO population relationships and AVB trust/topology semantics remain
    canonical upstream semantics and are not converted into ordinary build
    dependency edges.
    """

    @classmethod
    def project(
        cls,
        reconstruction,
        *,
        identity,
        boot_component_evidence,
        boot_construction_plan,
        native_boot_build_plan,
        avb_build_plan,
        existing_realizations: tuple[
            AndroidDeviceTreeBuildRealization,
            ...,
        ],
    ) -> tuple[
        AndroidDeviceTreeBuildRealization,
        ...,
    ]:
        from treeforge.android.reconstruction.build_system.model import (
            AndroidReconstructionBuildRepresentationKind,
        )
        from treeforge.android.device_tree.boot_component_evidence import (
            AndroidDeviceTreeBootComponentEvidence,
            AndroidDeviceTreeBootComponentSourceEquivalence,
        )
        from treeforge.android.device_tree.boot_construction import (
            AndroidDeviceTreeBootConstructionPlan,
        )
        from treeforge.android.device_tree.native_boot_build import (
            AndroidDeviceTreeNativeBootBuildPlan,
        )
        from treeforge.android.device_tree.avb_build_config import (
            AndroidDeviceTreeAvbBuildPlan,
        )
        from treeforge.android.device_tree.model import (
            AndroidDeviceTreeIdentity,
        )
        from treeforge.android.reconstruction.model import (
            AndroidReconstructionResult,
        )

        if not isinstance(
            identity,
            AndroidDeviceTreeIdentity,
        ):
            raise TypeError(
                "identity must be an "
                "AndroidDeviceTreeIdentity"
            )

        if not isinstance(
            reconstruction,
            AndroidReconstructionResult,
        ):
            raise TypeError(
                "reconstruction must be an "
                "AndroidReconstructionResult"
            )

        if not isinstance(
            existing_realizations,
            tuple,
        ):
            raise TypeError(
                "existing_realizations must be a tuple"
            )

        if not all(
            isinstance(
                realization,
                AndroidDeviceTreeBuildRealization,
            )
            for realization
            in existing_realizations
        ):
            raise TypeError(
                "existing_realizations must contain only "
                "AndroidDeviceTreeBuildRealization values"
            )

        if not isinstance(
            boot_component_evidence,
            tuple,
        ):
            raise TypeError(
                "boot_component_evidence must be a tuple"
            )

        if not all(
            isinstance(
                evidence,
                AndroidDeviceTreeBootComponentEvidence,
            )
            for evidence
            in boot_component_evidence
        ):
            raise TypeError(
                "boot_component_evidence contains an invalid model"
            )

        if not isinstance(
            boot_construction_plan,
            AndroidDeviceTreeBootConstructionPlan,
        ):
            raise TypeError(
                "boot_construction_plan must be an "
                "AndroidDeviceTreeBootConstructionPlan"
            )

        if not isinstance(
            native_boot_build_plan,
            AndroidDeviceTreeNativeBootBuildPlan,
        ):
            raise TypeError(
                "native_boot_build_plan must be an "
                "AndroidDeviceTreeNativeBootBuildPlan"
            )

        if not isinstance(
            avb_build_plan,
            AndroidDeviceTreeAvbBuildPlan,
        ):
            raise TypeError(
                "avb_build_plan must be an "
                "AndroidDeviceTreeAvbBuildPlan"
            )

        target_kinds = {
            AndroidReconstructionBuildRepresentationKind
            .BOOT_ARTIFACT,
            AndroidReconstructionBuildRepresentationKind
            .DTBO_ARTIFACT,
            AndroidReconstructionBuildRepresentationKind
            .VBMETA_ARTIFACT,
        }

        target_representations = tuple(
            representation
            for representation
            in reconstruction.artifact_build_representations
            if representation.kind in target_kinds
        )

        target_representation_ids = {
            representation.representation_id
            for representation
            in target_representations
        }

        existing_representation_ids = {
            realization.representation_id
            for realization
            in existing_realizations
        }

        overlap = (
            target_representation_ids
            & existing_representation_ids
        )

        if overlap:
            raise ValueError(
                "boot/DTBO/VBMeta realization population overlaps "
                "existing Device Tree representation coverage: "
                f"{sorted(overlap)!r}"
            )

        all_representation_ids = {
            representation.representation_id
            for representation
            in reconstruction.artifact_build_representations
        }

        universe = (
            reconstruction
            .reconstruction_input
            .runtime_linking
            .universe
        )

        partition_layout = (
            reconstruction
            .reconstruction_input
            .partition_layout
        )

        boot_compositions = (
            reconstruction
            .boot_image_compositions
        )

        boot_compositions_by_requirement_id = {
            composition.requirement_id:
            composition
            for composition
            in boot_compositions
        }

        if len(
            boot_compositions_by_requirement_id
        ) != len(
            boot_compositions
        ):
            raise ValueError(
                "Reconstruction boot-image composition identities "
                "must be unique before Device Tree realization"
            )

        boot_requirements_by_id = {
            composition.requirement_id:
            composition.requirement
            for composition
            in boot_compositions
        }

        # BOARD_BOOT_HEADER_VERSION is shared by the standard Android
        # boot/init_boot/vendor_boot build surface.
        #
        # Other canonical boot-family compositions remain fully preserved,
        # but their independent header semantics must not invalidate this
        # shared BoardConfig value.
        board_config_boot_header_partitions = frozenset(
            {
                "boot",
                "init_boot",
                "vendor_boot",
            }
        )

        boot_header_versions = {
            composition
            .requirement
            .semantics
            .header_version
            for composition
            in boot_compositions
            if (
                composition
                .requirement
                .partition
                .name
                in board_config_boot_header_partitions
            )
        }

        boot_component_evidence_by_requirement_id = {}

        for evidence in boot_component_evidence:
            canonical_composition = (
                boot_compositions_by_requirement_id.get(
                    evidence.requirement_id
                )
            )

            if canonical_composition is None:
                raise ValueError(
                    "boot component evidence references an unknown "
                    "Reconstruction boot-image composition: "
                    f"{evidence.requirement_id}"
                )

            if (
                evidence.composition
                is not canonical_composition
            ):
                raise ValueError(
                    "boot component evidence changed exact "
                    "Reconstruction composition identity"
                )

            boot_component_evidence_by_requirement_id.setdefault(
                evidence.requirement_id,
                [],
            ).append(
                evidence
            )

        expected_component_ids = {
            (
                composition.requirement_id,
                artifact.semantic_name,
            )
            for composition
            in boot_compositions
            for artifact
            in composition.component_artifacts
        }

        actual_component_ids = {
            (
                evidence.requirement_id,
                evidence.semantic_name,
            )
            for evidence
            in boot_component_evidence
        }

        if actual_component_ids != expected_component_ids:
            missing = sorted(
                expected_component_ids
                - actual_component_ids
            )

            unexpected = sorted(
                actual_component_ids
                - expected_component_ids
            )

            raise ValueError(
                "Device Tree boot component evidence must cover "
                "the complete Reconstruction component population: "
                f"missing={missing!r}, "
                f"unexpected={unexpected!r}"
            )

        canonical_boot_header_version = (
            next(iter(boot_header_versions))
            if len(boot_header_versions) == 1
            else None
        )

        dtbo_container = reconstruction.dtbo_container

        dtbo_container_requirement_ids = (
            set(dtbo_container.requirement_ids)
            if dtbo_container is not None
            else set()
        )

        realizations = []

        for representation in target_representations:
            if (
                representation.canonical_requirement_id
                is None
            ):
                raise ValueError(
                    "boot/DTBO/VBMeta Device Tree realization "
                    "requires canonical requirement-backed identity: "
                    f"{representation.representation_id}"
                )

            if (
                representation.source_content_id is not None
                or representation.preserved_artifact_id is not None
                or representation.source_module_id is not None
            ):
                raise ValueError(
                    "step-10 board/image realization encountered "
                    "unexpected non-requirement payload identity: "
                    f"{representation.representation_id}"
                )

            missing_dependency_ids = (
                set(representation.dependency_ids)
                - all_representation_ids
            )

            if missing_dependency_ids:
                raise ValueError(
                    "board/image representation references missing "
                    "Reconstruction dependency identities: "
                    f"{representation.representation_id}, "
                    f"missing={sorted(missing_dependency_ids)!r}"
                )

            if representation.dependency_ids:
                raise ValueError(
                    "boot/DTBO/VBMeta representation unexpectedly "
                    "carries ordinary physical build dependencies: "
                    f"{representation.representation_id}"
                )

            status = (
                AndroidDeviceTreeBuildRealizationStatus
                .PARTIAL
            )

            source_path = None

            if (
                representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .BOOT_ARTIFACT
            ):
                requirement = (
                    boot_requirements_by_id.get(
                        representation.canonical_requirement_id
                    )
                )

                composition = (
                    boot_compositions_by_requirement_id.get(
                        representation.canonical_requirement_id
                    )
                )

                if requirement is None:
                    reason = (
                        "Canonical boot build representation has no "
                        "matching Reconstruction boot-image composition."
                    )

                elif composition is None:
                    reason = (
                        "Canonical boot build representation has no "
                        "matching Reconstruction boot-image composition."
                    )

                elif (
                    composition.requirement
                    is not requirement
                ):
                    raise ValueError(
                        "Device Tree boot realization lost exact "
                        "Reconstruction requirement identity"
                    )

                elif (
                    composition.image_artifact
                    is not requirement.partition.artifact
                ):
                    raise ValueError(
                        "Device Tree boot realization lost exact "
                        "canonical image artifact identity"
                    )

                elif (
                    requirement.partition.name
                    in board_config_boot_header_partitions
                    and canonical_boot_header_version
                    is None
                ):
                    reason = (
                        "Concrete Boot BoardConfig integration cannot "
                        "select one canonical shared boot header version "
                        "because the BoardConfig-managed "
                        "boot/init_boot/vendor_boot evidence disagrees."
                    )

                elif partition_layout is None:
                    reason = (
                        "Concrete Boot BoardConfig integration has no "
                        "canonical PartitionLayout evidence available for "
                        "this run, so partition capacity is not guessed."
                    )

                elif (
                    partition_layout.partition(
                        requirement.partition.name
                    )
                    is None
                ):
                    reason = (
                        "Concrete Boot BoardConfig integration cannot "
                        "find the exact canonical boot partition identity "
                        "in PartitionLayout."
                    )

                elif (
                    partition_layout.partition(
                        requirement.partition.name
                    ).size_bytes
                    is None
                ):
                    reason = (
                        "Concrete Boot BoardConfig integration lacks "
                        "Layout-owned partition-size evidence for this "
                        "boot-family requirement."
                    )

                else:
                    component_evidence = tuple(
                        sorted(
                            boot_component_evidence_by_requirement_id.get(
                                representation.canonical_requirement_id,
                                (),
                            ),
                            key=lambda item: (
                                item.semantic_name
                            ),
                        )
                    )

                    component_names = tuple(
                        item.semantic_name
                        for item
                        in component_evidence
                    )

                    expected_names = tuple(
                        sorted(
                            artifact.semantic_name
                            for artifact
                            in composition.component_artifacts
                        )
                    )

                    if component_names != expected_names:
                        raise ValueError(
                            "Device Tree boot component evidence "
                            "changed canonical image composition"
                        )

                    exact_factory_count = sum(
                        item.exact_factory_payload_available
                        for item
                        in component_evidence
                    )

                    missing_factory_count = (
                        len(component_evidence)
                        - exact_factory_count
                    )

                    source_resolved_count = sum(
                        item.source_equivalence
                        is
                        AndroidDeviceTreeBootComponentSourceEquivalence
                        .RESOLVED
                        for item
                        in component_evidence
                    )

                    source_partial_count = sum(
                        item.source_equivalence
                        is
                        AndroidDeviceTreeBootComponentSourceEquivalence
                        .PARTIAL
                        for item
                        in component_evidence
                    )

                    source_unresolved_count = sum(
                        item.source_equivalence
                        is
                        AndroidDeviceTreeBootComponentSourceEquivalence
                        .UNRESOLVED
                        for item
                        in component_evidence
                    )

                    if (
                        source_resolved_count
                        + source_partial_count
                        + source_unresolved_count
                        != len(component_evidence)
                    ):
                        raise ValueError(
                            "Device Tree boot component "
                            "source-equivalence classification "
                            "coverage mismatch"
                        )

                    construction_image = (
                        boot_construction_plan
                        .image_for_partition(
                            requirement.partition.name
                        )
                    )

                    if construction_image is not None:
                        if (
                            construction_image.requirement_id
                            != requirement.requirement_id
                        ):
                            raise ValueError(
                                "boot construction input changed exact "
                                "canonical requirement identity"
                            )

                        status = (
                            AndroidDeviceTreeBuildRealizationStatus
                            .RESOLVED
                        )

                        source_path = (
                            construction_image.destination
                        )

                        reason = None

                    elif (
                        native_boot_build_plan
                        .resolves_partition(
                            requirement.partition.name
                        )
                    ):
                        status = (
                            AndroidDeviceTreeBuildRealizationStatus
                            .RESOLVED
                        )

                        source_path = (
                            native_boot_build_plan
                            .source_path_for_partition(
                                requirement.partition.name
                            )
                        )

                        if source_path is None:
                            raise ValueError(
                                "resolved Android-native boot "
                                "construction lost its build-file path"
                            )

                        reason = None

                    else:
                        reason = (
                            "Factory-derived Boot realization preserves the "
                            "canonical header version, partition size, exact "
                            "image identity, and exact component population "
                            f"{component_names!r}. Exact factory payloads are "
                            f"available for {exact_factory_count}/"
                            f"{len(component_evidence)} components"
                        )

                        if missing_factory_count:
                            reason += (
                                f"; {missing_factory_count} canonical "
                                "component payload(s) are not materially "
                                "accessible"
                            )

                        reason += (
                            ". Source-equivalent realization is "
                            f"resolved={source_resolved_count}, "
                            f"partial={source_partial_count}, "
                            f"unresolved={source_unresolved_count}. "
                            "No proven Android construction mechanism has "
                            "yet been selected for this partition. Exact "
                            "factory bytes still do not prove source ownership "
                            "or the original OEM build recipe."
                        )

            elif (
                representation.kind
                is AndroidReconstructionBuildRepresentationKind
                .DTBO_ARTIFACT
            ):
                if dtbo_container is None:
                    reason = (
                        "Canonical DTBO population lacks the syntax-neutral "
                        "shared Reconstruction container required for "
                        "concrete prebuilt-image integration."
                    )

                elif (
                    representation.canonical_requirement_id
                    not in dtbo_container_requirement_ids
                ):
                    reason = (
                        "Canonical DTBO representation is not covered by "
                        "the exact shared Reconstruction DTBO container."
                    )

                elif (
                    not dtbo_container.artifact.path.is_file()
                ):
                    reason = (
                        "Canonical shared DTBO container is not "
                        "materially accessible for Device Tree integration."
                    )

                else:
                    status = (
                        AndroidDeviceTreeBuildRealizationStatus
                        .RESOLVED
                    )

                    source_path = (
                        PurePosixPath(
                            identity.device_root.as_posix()
                        )
                        / "boot"
                        / "dtbo.img"
                    )

                    reason = None

            else:
                avb_node = (
                    avb_build_plan
                    .node_for_requirement_id(
                        representation
                        .canonical_requirement_id
                    )
                )

                if avb_node is None:
                    reason = (
                        "Canonical partition-backed VBMeta representation "
                        "has no matching Android AVB build configuration."
                    )

                elif not avb_build_plan.complete:
                    reason = (
                        "Canonical AVB topology has not been mapped "
                        "completely onto Android build configuration."
                    )

                else:
                    status = (
                        AndroidDeviceTreeBuildRealizationStatus
                        .RESOLVED
                    )

                    source_path = (
                        avb_build_plan
                        .board_config_path
                    )

                    reason = None

            realizations.append(
                AndroidDeviceTreeBuildRealization(
                    realization_id=(
                        "device-tree-realization:"
                        f"{representation.representation_id}"
                    ),
                    kind=(
                        AndroidDeviceTreeBuildRealizationKind
                        .BOARD_CONFIGURATION
                    ),
                    status=status,
                    build_representation=representation,
                    source_path=source_path,
                    module_name=None,
                    dependency_realization_ids=(),
                    reason=reason,
                )
            )

        result = tuple(
            sorted(
                realizations,
                key=lambda realization: (
                    realization.realization_id
                ),
            )
        )

        represented_ids = {
            realization.representation_id
            for realization
            in result
        }

        if represented_ids != target_representation_ids:
            raise ValueError(
                "Device Tree boot/DTBO/VBMeta realization "
                "coverage mismatch"
            )

        if len(result) != len(represented_ids):
            raise ValueError(
                "Device Tree boot/DTBO/VBMeta realizations must "
                "cover each Reconstruction representation exactly once"
            )

        expected_counts = {
            kind: sum(
                representation.kind is kind
                for representation
                in target_representations
            )
            for kind in target_kinds
        }

        actual_counts = {
            kind: sum(
                realization.build_representation.kind is kind
                for realization
                in result
            )
            for kind in target_kinds
        }

        if actual_counts != expected_counts:
            raise ValueError(
                "Device Tree boot/DTBO/VBMeta family coverage mismatch"
            )

        return result
